TEST_F(BeeperTest, PortOutGeneratesBandLimitedOutput)
{
    Beeper& beeper = sm->getBeeper();

    sm->handleFrameStart();
    // Simulate port #FE write with EAR=1 (bit 4) at T=1000
    beeper.handlePortOut(0b0001'0000, 1000);
    sm->handleFrameEnd();

    const int16_t* buffer = sm->deviceBuffer(AudioSourceType::Beeper);
    ASSERT_NE(buffer, nullptr);

    // After step delta, samples after T=1000 should show high amplitude (~7500)
    int nonZeroCount = 0;
    for (size_t i = 0; i < SAMPLES_PER_FRAME * 2; i++)
    {
        if (std::abs(buffer[i]) > 1000)
            nonZeroCount++;
    }
    EXPECT_GT(nonZeroCount, 100);
}

