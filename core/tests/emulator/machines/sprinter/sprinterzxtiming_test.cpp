// ESC at BIOS 3.06's boot prompt: the BIOS's own ZX mode, the default Pentagon timing (320 lines, 71 680 T,
// Pentagon INT), 3.5 MHz unless the CMOS says turbo; TR-DOS from the floppy, RUN: zxtime measures a 71 680-T
// frame, one INT per frame, no original waits (ALL_MODE #FE)
// Boot-bound (BIOS POST, its prompt, the ZX menu, TR-DOS loading zxtime from the floppy, 50 + 34 measured
// frames): ~1 s host time with the turbo mode
TEST_F(SprinterZxTimeEsc_Test, Pentagon_FrameIntAndNoWaits)
{
    const ZxTimeProgram p = BuildZxTime();
    ASSERT_FALSE(p.bytes.empty());
    const std::string trd = TestPathHelper::GetUniqueTestScratchPath("zxtime.trd");
    std::vector<uint8_t> image = ZxProgramFiles::BuildTrd("zxtime", kOrg, p.bytes);
    ASSERT_TRUE(FileHelper::SaveBufferToFile(trd, image.data(), image.size()));
    std::string error;
    ASSERT_TRUE(_emulator->LoadDisk(trd, 0, &error)) << error;

    const char* prompt = "<ESC> TO ZX-MODE";
    auto promptShown = [&]() {
        const SprinterVideoRam& vram = _decoder->GetVideoRam();
        std::string text;
        for (uint8_t page = 0; page < 2; page++)
            for (uint8_t b = 0; b < 32; b++)
                for (uint8_t a = 0; a < 40; a++)
                    for (uint8_t half = 0; half < 2; half++)
                    {
                        const uint8_t c = vram.Read((1u + 2u * a + half + 0x80u * page) * 1024u + 0x301 + 4u * b);
                        text.push_back((c >= 0x20 && c < 0x7F) ? static_cast<char>(c) : ' ');
                    }
        return text.find(prompt) != std::string::npos;
    };
    EmulatorTestHelper::RunUntil(_emulator.get(), promptShown, 1200, 5);
    ASSERT_TRUE(promptShown());
    Zx("pc.esc", 10);
    EmulatorTestHelper::RunUntil(_emulator.get(), [&] { return SpectrumHas("TR-DOS"); }, 600, 10);
    ASSERT_TRUE(SpectrumHas("TR-DOS")) << ScreenOCR::ocrScreen(_emulator->GetId());
    EmulatorTestHelper::RunFramesFast(_emulator.get(), 30);
    Zx("enter", 80);  // the menu's first entry: TR-DOS
    Zx("r", 6);       // RUN (keyword mode): boot loads and starts zxtime
    Zx("enter", 6);
    const uint16_t done = p.Sym("DONE");
    EmulatorTestHelper::RunUntil(_emulator.get(), [&] { return _context->pMemory->DirectReadFromZ80Memory(done) == 1; }, 2000, 10);
    const ZxTimeResult r = ReadResult(*_context->pMemory, p);
    ASSERT_TRUE(r.done) << ScreenOCR::ocrScreen(_emulator->GetId());
    std::printf("[ zxtime ESC ] %s\n%s\n", Describe(r).c_str(), ScreenOCR::ocrScreen(_emulator->GetId()).c_str());
    RecordProperty("zxtime", Describe(r));

    EXPECT_EQ((_decoder->GetPldState().allMode & 0x04), 0x04) << "the default ZX mode keeps the original waits off";
    if (!r.turbo)
    {
        EXPECT_EQ(r.frameT, 71680u) << Describe(r);
        EXPECT_EQ(r.Extra4000(), 0u) << Describe(r);
        EXPECT_EQ(r.ExtraC5(), 0u) << Describe(r);
    }
    EXPECT_EQ(r.ints, 50u) << Describe(r);
    EXPECT_EQ(r.repeats, 0u) << "the acknowledge ends the pulse; " << Describe(r);
    EXPECT_TRUE(SpectrumHas("Done.")) << ScreenOCR::ocrScreen(_emulator->GetId());
}

