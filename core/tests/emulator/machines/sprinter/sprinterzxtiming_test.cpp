// The tape through the ROM loader, in real time (the fast-load trap off): zxtime.tap (a BASIC loader that loads and
// starts the code) from 48 BASIC's LOAD "". P128.ZX runs the ROM at 3.5 MHz: the program loads and runs. SP.ZX runs
// it at 21 MHz: the loader's edge timing is six times too short for the tape, nothing loads - as on the board, whose
// tape input (KMPS) is played in real time (research-zx-mode.md §8)
// Boot-bound (BIOS, DSS 1.71, two launcher runs, ~11 s of tape each): ~6 s host time
TEST_F(SprinterZxTimeModes_Test, Tape_LoadsAt35MhzNotInTurbo)
{
    const ZxTimeProgram p = BuildZxTime();
    ASSERT_FALSE(p.bytes.empty());
    const std::string tap = ZxTimePath("zxtime.tap");
    ASSERT_TRUE(FileHelper::FileExists(tap));
    ASSERT_TRUE(_context->pFeatureManager->setFeature(Features::kFastTape, false));
    ASSERT_NO_FATAL_FAILURE(BootToPrompt());

    const uint16_t done = p.Sym("DONE");
    for (const char* mode : {"p128.zx", "sp.zx"})
    {
        SCOPED_TRACE(mode);
        const bool turbo = std::strcmp(mode, "sp.zx") == 0;
        for (uint16_t i = 0; i < 16; i++)
            _context->pMemory->DirectWriteToZ80Memory(static_cast<uint16_t>(kOrg + i), 0);
        ASSERT_NO_FATAL_FAILURE(Launch(mode));
        for (int i = 0; i < 4; i++)
            Zx("down", 10);  // TR-DOS, Hardware, 128 BASIC, Calculator, 48 BASIC
        Zx("enter", 100);
        SaveScreen(std::string("tape-48basic-") + mode + ".png");
        ASSERT_TRUE(SpectrumHas("Sinclair")) << "48 BASIC; " << SpectrumText();
        std::string error;
        ASSERT_TRUE(_emulator->LoadTape(tap, &error)) << error;
        Zx("j", 6);  // LOAD
        Keys()->TapCombo({"symbol", "p"}, 3);
        EmulatorTestHelper::RunFramesFast(_emulator.get(), 6);
        Keys()->TapCombo({"symbol", "p"}, 3);
        EmulatorTestHelper::RunFramesFast(_emulator.get(), 6);
        Zx("enter", 6);
        EmulatorTestHelper::RunUntil(_emulator.get(), [&] { return _context->pMemory->DirectReadFromZ80Memory(done) == 1; }, 1500, 10);
        SaveScreen(std::string("tape-") + mode + ".png");
        bool loaded = true;
        for (size_t i = 0; i < 16 && i < p.bytes.size(); i++)
            loaded = loaded && _context->pMemory->DirectReadFromZ80Memory(static_cast<uint16_t>(kOrg + i)) == p.bytes[i];
        if (turbo)
        {
            EXPECT_EQ(_decoder->GetPldState().turbo, 1);
            EXPECT_FALSE(loaded) << "21 MHz: the ROM loader cannot read a real-time tape; " << SpectrumText();
            EXPECT_NE(_context->pMemory->DirectReadFromZ80Memory(done), 1);
        }
        else
        {
            EXPECT_EQ(_decoder->GetPldState().turbo, 0);
            EXPECT_TRUE(loaded) << SpectrumText();
            EXPECT_EQ(_context->pMemory->DirectReadFromZ80Memory(done), 1) << SpectrumText();
            EXPECT_TRUE(SpectrumHas("FRAME  71680 T")) << SpectrumText();
        }
        _emulator->GetContext()->pTape->stopPlayback();
        CtrlAltDel(20);
        EmulatorTestHelper::RunUntil(_emulator.get(), [&] { return !InZxMode(); }, 300, 10);
        ASSERT_FALSE(InZxMode());
        EmulatorTestHelper::RunFramesFast(_emulator.get(), 200);
    }
}

