TEST_F(LoaderHobeta_Test, Inject_IntoBlankDisk)
{
    std::vector<uint8_t> file = readFile(fixture("loaders/hobeta/hello.$C"));
    std::vector<uint8_t> body(file.begin() + 17, file.end());

    LoaderHobeta loader(_context, fixture("loaders/hobeta/hello.$C"));
    ASSERT_TRUE(loader.loadImage()) << join(loader.lastWarnings(), "; ");
    DiskImage* image = loader.getImage();
    ASSERT_NE(image, nullptr);
    EXPECT_EQ(image->getCylinders(), 80);
    EXPECT_EQ(image->getSides(), 2);
    EXPECT_TRUE(image->getLoaded());
    EXPECT_FALSE(image->isDirty()) << "a freshly built disk has nothing to save back";
    EXPECT_TRUE(LoaderTRD::isTrdosGeometry(image));

    // Catalog entry
    std::vector<LoaderHobeta::CatalogEntry> files = LoaderHobeta::listFiles(image);
    ASSERT_EQ(files.size(), 1u);
    EXPECT_EQ(files[0].index, 0);
    const TRDOSDirectoryEntry& entry = files[0].entry;
    EXPECT_EQ(std::string(entry.Name, 8), "hello   ");
    EXPECT_EQ(entry.Type, 'C');
    EXPECT_EQ(entry.Start, 0x8000);
    EXPECT_EQ(entry.Length, 700);
    EXPECT_EQ(entry.SizeInSectors, 3);
    EXPECT_EQ(entry.StartTrack, 1) << "first free track of a blank disk";
    EXPECT_EQ(entry.StartSector, 0);

    // Same entry as seen in the raw catalog sector 1
    DiskImage::Track* track0 = image->getTrackForCylinderAndSide(0, 0);
    DiskImage::Sector* catalog = track0->getSector(0);
    EXPECT_EQ(std::memcmp(catalog->data, &entry, sizeof(TRDOSDirectoryEntry)), 0);
    EXPECT_EQ(catalog->data[16], 0) << "next catalog slot stays empty";
    EXPECT_TRUE(catalog->isDataCRCValid());

    // Volume sector counters
    TRDVolumeInfo* volume = volumeOf(image);
    EXPECT_EQ(volume->trDOSSignature, TRD_SIGNATURE);
    EXPECT_EQ(volume->fileCount, 1);
    EXPECT_EQ(volume->deletedFileCount, 0);
    EXPECT_EQ(volume->freeSectorCount, TRD_FREE_SECTORS_ON_DS_80_EMPTY_DISK - 3);
    EXPECT_EQ(volume->firstFreeTrack, 1);
    EXPECT_EQ(volume->firstFreeSector, 3);
    EXPECT_TRUE(track0->getSector(TRD_VOLUME_SECTOR)->isDataCRCValid());

    // Data readable via getSector (TR-DOS track 1 = cylinder 0 side 1, sectors 1..3)
    expectFileOnDisk(image, entry, body);
    DiskImage::Track* track1 = image->getTrackForCylinderAndSide(0, 1);
    EXPECT_EQ(track1, image->getTrack(1));
    EXPECT_EQ(std::memcmp(track1->getSector(0)->data, body.data(), 256), 0);
    EXPECT_EQ(std::memcmp(track1->getSector(2)->data, body.data() + 512, 256), 0);

    // Untouched sector after the file is still blank
    bool blank = true;
    for (size_t i = 0; i < 256; i++) blank = blank && track1->getSector(3)->data[i] == 0;
    EXPECT_TRUE(blank);

    // ... and through the WD1793
    for (uint8_t n = 0; n < 3; n++)
    {
        std::vector<uint8_t> read = readThroughController(image, 0, 1, static_cast<uint8_t>(n + 1));
        ASSERT_EQ(read.size(), 256u) << "sector " << (int)(n + 1);
        EXPECT_EQ(std::memcmp(read.data(), body.data() + n * 256, 256), 0) << "sector " << (int)(n + 1);
    }

    // The image validates as a TR-DOS disk
    LoaderTRD trd(_context, "");
    TRDValidationReport report;
    EXPECT_TRUE(trd.validateTRDOSImage(image, report));

    delete image;
}

TEST_F(LoaderHobeta_Test, Inject_IntoExistingDisk_AppendsAfterLastFile)
{
    std::vector<uint8_t> file = readFile(fixture("loaders/hobeta/hello.$C"));
    std::vector<uint8_t> body(file.begin() + 17, file.end());

    // insult.scl: 4 files, 731 sectors
    LoaderSCL scl(_context, fixture("loaders/scl/insult.scl"));
    ASSERT_TRUE(scl.loadImage());
    DiskImage* image = scl.getImage();
    ASSERT_NE(image, nullptr);
    image->markClean();

    TRDVolumeInfo* volume = volumeOf(image);
    const uint8_t prevFileCount = volume->fileCount;
    const uint16_t prevFree = volume->freeSectorCount;
    const uint8_t prevFirstFreeTrack = volume->firstFreeTrack;
    const uint8_t prevFirstFreeSector = volume->firstFreeSector;
    ASSERT_EQ(prevFileCount, 4);
    ASSERT_EQ(prevFree, TRD_FREE_SECTORS_ON_DS_80_EMPTY_DISK - 731);
    ASSERT_EQ(prevFirstFreeTrack * 16 + prevFirstFreeSector, 16 + 731);

    std::vector<LoaderHobeta::CatalogEntry> before = LoaderHobeta::listFiles(image);
    ASSERT_EQ(before.size(), 4u);
    const TRDOSDirectoryEntry last = before.back().entry;
    EXPECT_EQ(std::string(last.Name, 8), "boot    ");
    EXPECT_EQ(last.StartTrack * 16 + last.StartSector + last.SizeInSectors, prevFirstFreeTrack * 16 + prevFirstFreeSector)
        << "the last file ends exactly at the first free sector";

    LoaderHobeta loader(_context, fixture("loaders/hobeta/hello.$C"));
    TRDOSDirectoryEntry placed;
    ASSERT_TRUE(loader.injectInto(image, &placed)) << join(loader.lastWarnings(), "; ");
    EXPECT_TRUE(loader.lastWarnings().empty());
    EXPECT_EQ(loader.getImage(), nullptr) << "injectInto does not adopt the image";

    // Placement: right after the previous last file, as recorded in the volume sector
    EXPECT_EQ(placed.StartTrack, prevFirstFreeTrack);
    EXPECT_EQ(placed.StartSector, prevFirstFreeSector);
    EXPECT_EQ(std::string(placed.Name, 8), "hello   ");
    EXPECT_EQ(placed.SizeInSectors, 3);

    // Catalog: appended as entry 4
    std::vector<LoaderHobeta::CatalogEntry> after = LoaderHobeta::listFiles(image);
    ASSERT_EQ(after.size(), 5u);
    EXPECT_EQ(after[4].index, 4);
    EXPECT_EQ(std::memcmp(&after[4].entry, &placed, sizeof(TRDOSDirectoryEntry)), 0);
    for (size_t i = 0; i < 4; i++)
    {
        EXPECT_EQ(std::memcmp(&after[i].entry, &before[i].entry, sizeof(TRDOSDirectoryEntry)), 0) << "existing entry " << i << " unchanged";
    }

    // Volume sector counters
    volume = volumeOf(image);
    EXPECT_EQ(volume->fileCount, prevFileCount + 1);
    EXPECT_EQ(volume->freeSectorCount, prevFree - 3);
    EXPECT_EQ((volume->firstFreeTrack * 16 + volume->firstFreeSector), prevFirstFreeTrack * 16 + prevFirstFreeSector + 3);

    // Body in the chain, CRCs valid, the disk is now dirty (it has unsaved changes)
    expectFileOnDisk(image, placed, body);
    EXPECT_TRUE(image->isDirty());
    EXPECT_TRUE(image->getTrackForCylinderAndSide(0, 0)->isDirty());
    EXPECT_TRUE(image->getTrack(placed.StartTrack)->isDirty());

    // Still a valid TR-DOS disk that can be written back as TRD
    LoaderTRD trd(_context, "");
    TRDValidationReport report;
    EXPECT_TRUE(trd.validateTRDOSImage(image, report));

    // The first sector of the injected file is readable through the controller
    // (TR-DOS track t = cylinder t / 2, side t % 2)
    std::vector<uint8_t> read = readThroughController(image, static_cast<uint8_t>(placed.StartTrack / 2),
                                                      static_cast<uint8_t>(placed.StartTrack % 2),
                                                      static_cast<uint8_t>(placed.StartSector + 1));
    ASSERT_EQ(read.size(), 256u);
    EXPECT_EQ(std::memcmp(read.data(), body.data(), 256), 0);

    delete image;
}

TEST_F(LoaderHobeta_Test, Inject_NotEnoughSpace)
{
    // Free space below the 3 sectors the file needs
    {
        DiskImage* image = blankTrdos();
        TRDVolumeInfo* volume = volumeOf(image);
        volume->freeSectorCount = 2;
        image->getTrackForCylinderAndSide(0, 0)->getSector(TRD_VOLUME_SECTOR)->recalculateDataCRC();
        image->markClean();

        std::vector<std::vector<uint8_t>> before = snapshot(image);

        LoaderHobeta loader(_context, fixture("loaders/hobeta/hello.$C"));
        TRDOSDirectoryEntry placed;
        EXPECT_FALSE(loader.injectInto(image, &placed));
        ASSERT_FALSE(loader.lastWarnings().empty());
        EXPECT_NE(loader.lastWarnings().front().find("refused"), std::string::npos) << loader.lastWarnings().front();

        EXPECT_FALSE(image->isDirty()) << "dirty flag unchanged";
        EXPECT_EQ(snapshot(image), before) << "image untouched";
        EXPECT_EQ(volumeOf(image)->fileCount, 0);
        EXPECT_EQ(volumeOf(image)->freeSectorCount, 2);
        EXPECT_TRUE(LoaderHobeta::listFiles(image).empty());
        delete image;
    }

    // Exactly enough space is accepted
    {
        DiskImage* image = blankTrdos();
        volumeOf(image)->freeSectorCount = 3;
        image->getTrackForCylinderAndSide(0, 0)->getSector(TRD_VOLUME_SECTOR)->recalculateDataCRC();
        image->markClean();

        LoaderHobeta loader(_context, fixture("loaders/hobeta/hello.$C"));
        EXPECT_TRUE(loader.injectInto(image)) << join(loader.lastWarnings(), "; ");
        EXPECT_EQ(volumeOf(image)->freeSectorCount, 0);
        EXPECT_TRUE(image->isDirty());
        delete image;
    }

    // Catalog full (128 files)
    {
        DiskImage* image = blankTrdos();
        volumeOf(image)->fileCount = TRD_MAX_FILES;
        image->getTrackForCylinderAndSide(0, 0)->getSector(TRD_VOLUME_SECTOR)->recalculateDataCRC();
        image->markClean();
        std::vector<std::vector<uint8_t>> before = snapshot(image);

        LoaderHobeta loader(_context, fixture("loaders/hobeta/hello.$C"));
        EXPECT_FALSE(loader.injectInto(image));
        ASSERT_FALSE(loader.lastWarnings().empty());
        EXPECT_NE(loader.lastWarnings().front().find("full"), std::string::npos) << loader.lastWarnings().front();
        EXPECT_FALSE(image->isDirty());
        EXPECT_EQ(snapshot(image), before);
        delete image;
    }

    // First free sector points past the end of the disk (chain would leave the geometry)
    {
        DiskImage* image = blankTrdos();
        volumeOf(image)->firstFreeTrack = 159;
        volumeOf(image)->firstFreeSector = 14;
        image->getTrackForCylinderAndSide(0, 0)->getSector(TRD_VOLUME_SECTOR)->recalculateDataCRC();
        image->markClean();
        std::vector<std::vector<uint8_t>> before = snapshot(image);

        LoaderHobeta loader(_context, fixture("loaders/hobeta/hello.$C"));
        EXPECT_FALSE(loader.injectInto(image));
        EXPECT_FALSE(loader.lastWarnings().empty());
        EXPECT_FALSE(image->isDirty());
        EXPECT_EQ(snapshot(image), before);
        delete image;
    }

    // Not a TR-DOS disk at all: +D geometry on every track
    {
        DiskImage image(80, 2, Spec::plusD());
        std::vector<std::vector<uint8_t>> before = snapshot(&image);

        LoaderHobeta loader(_context, fixture("loaders/hobeta/hello.$C"));
        EXPECT_FALSE(loader.injectInto(&image));
        ASSERT_FALSE(loader.lastWarnings().empty());
        EXPECT_NE(loader.lastWarnings().front().find("TR-DOS"), std::string::npos) << loader.lastWarnings().front();
        EXPECT_FALSE(image.isDirty());
        EXPECT_EQ(snapshot(&image), before);
        EXPECT_TRUE(LoaderHobeta::listFiles(&image).empty());
    }

    // TR-DOS system track, but the file would land on a track that is not TR-DOS (16 x 256)
    {
        DiskImage* image = blankTrdos();
        image->getTrack(1)->formatTrack(0, 1, Spec::plusD());   // TR-DOS track 1 = cylinder 0 side 1
        image->markClean();
        std::vector<std::vector<uint8_t>> before = snapshot(image);

        LoaderHobeta loader(_context, fixture("loaders/hobeta/hello.$C"));
        EXPECT_FALSE(loader.injectInto(image));
        ASSERT_FALSE(loader.lastWarnings().empty());
        EXPECT_NE(loader.lastWarnings().front().find("track 1"), std::string::npos) << loader.lastWarnings().front();
        EXPECT_FALSE(image->isDirty());
        EXPECT_EQ(snapshot(image), before);
        delete image;
    }
}

