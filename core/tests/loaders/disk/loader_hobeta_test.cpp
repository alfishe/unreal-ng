TEST_F(LoaderHobeta_Test, Detect_Checksum)
{
    std::vector<uint8_t> good = readFile(fixture("loaders/hobeta/hello.$C"));
    std::vector<uint8_t> bad = readFile(fixture("loaders/hobeta/bad-checksum.$C"));
    ASSERT_EQ(good.size(), 17u + 3 * 256);
    ASSERT_EQ(bad.size(), good.size());

    // Checksum formula: sum(header[i] * 257 + i), i = 0..14, 16-bit
    uint16_t expected = 0;
    for (size_t i = 0; i < 15; i++) expected = static_cast<uint16_t>(expected + good[i] * 257 + i);
    EXPECT_EQ(LoaderHobeta::computeChecksum(good.data()), expected);
    EXPECT_EQ(static_cast<uint16_t>(good[15] | (good[16] << 8)), expected);

    EXPECT_TRUE(LoaderHobeta::detect(good.data(), good.size()));
    EXPECT_FALSE(LoaderHobeta::detect(bad.data(), bad.size()));
    EXPECT_FALSE(LoaderHobeta::detect(good.data(), good.size() - 1)) << "size must match 17 + sectors * 256";
    EXPECT_FALSE(LoaderHobeta::detect(good.data(), 16));
    EXPECT_FALSE(LoaderHobeta::detect(nullptr, 0));

    // Decoded header
    LoaderHobeta::Header header;
    std::vector<std::string> warnings;
    ASSERT_TRUE(LoaderHobeta::parseHeader(good.data(), good.size(), header, warnings));
    EXPECT_EQ(header.nameString(), "hello   ");
    EXPECT_EQ(header.type, 'C');
    EXPECT_EQ(header.start, 0x8000);
    EXPECT_EQ(header.length, 700);
    EXPECT_EQ(header.reserved, 0);
    EXPECT_EQ(header.sectors, 3);
    EXPECT_EQ(header.checksum, expected);
    EXPECT_TRUE(warnings.empty());

    // Corrupted checksum is reported as such
    EXPECT_FALSE(LoaderHobeta::parseHeader(bad.data(), bad.size(), header, warnings));
    ASSERT_FALSE(warnings.empty());
    EXPECT_NE(warnings.front().find("checksum"), std::string::npos) << warnings.front();

    // serializeHeader reproduces the file header byte for byte
    uint8_t encoded[17];
    LoaderHobeta::serializeHeader(header, encoded);
    EXPECT_EQ(std::memcmp(encoded, good.data(), 17), 0);

    // Through the loader
    LoaderHobeta goodLoader(_context, fixture("loaders/hobeta/hello.$C"));
    EXPECT_TRUE(goodLoader.loadFile());
    EXPECT_TRUE(goodLoader.isFileLoaded());
    EXPECT_EQ(goodLoader.getFileData().size(), 3u * 256);
    EXPECT_EQ(std::memcmp(goodLoader.getFileData().data(), good.data() + 17, 3 * 256), 0);

    LoaderHobeta badLoader(_context, fixture("loaders/hobeta/bad-checksum.$C"));
    EXPECT_FALSE(badLoader.loadFile());
    EXPECT_FALSE(badLoader.isFileLoaded());
    EXPECT_FALSE(badLoader.lastWarnings().empty());
    EXPECT_FALSE(badLoader.loadImage());
    EXPECT_EQ(badLoader.getImage(), nullptr);

    LoaderHobeta missing(_context, fixture("loaders/hobeta/none.$C"));
    EXPECT_FALSE(missing.loadImage());
    EXPECT_FALSE(missing.lastWarnings().empty());
}

