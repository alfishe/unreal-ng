/// Hobeta ($-file) loader tests (docs/inprogress/2026-09-02-universal-track-model/loader-hobeta.md, section 4)
///
/// Fixtures: testdata/loaders/hobeta/hello.$C (CODE "hello", start 0x8000, length 700, 3 sectors) and
/// bad-checksum.$C (same file, corrupted checksum), generated by core/tests/emulator/io/fdc/tools/mgt_hobeta_generator.py

using Spec = DiskImage::TrackFormatSpec;

class LoaderHobeta_Test : public ::testing::Test
{
protected:
    EmulatorContext* _context = nullptr;
    CoreCUT* _core = nullptr;
    Z80* _z80 = nullptr;

protected:
    void SetUp() override
    {
        _context = new EmulatorContext(LoggerLevel::LogError);
        _context->pModuleLogger->TurnOffLoggingForAll();

        _core = new CoreCUT(_context);
        _z80 = new Z80(_context);
        _core->_z80 = _z80;
        _context->pCore = _core;
    }

    void TearDown() override
    {
        if (_context)
        {
            if (_context->pCore)
            {
                _core->_z80 = nullptr;
                delete _z80;
                _context->pCore = nullptr;
                delete _core;
            }
            delete _context;
        }
    }

    static std::vector<uint8_t> readFile(const std::string& path)
    {
        std::vector<uint8_t> result;
        if (FileHelper::FileExists(path))
        {
            size_t size = FileHelper::GetFileSize(path);
            result.resize(size);
            if (size > 0) FileHelper::ReadFileToBuffer(path, result.data(), size);
        }
        return result;
    }

    static void removeFile(const std::string& path)
    {
        std::error_code ec;
        std::filesystem::remove(path, ec);
    }

    static std::string join(const std::vector<std::string>& items, const char* separator = "; ")
    {
        std::string result;
        for (const std::string& item : items)
        {
            if (!result.empty()) result += separator;
            result += item;
        }
        return result;
    }

    static std::string fixture(const char* name) { return TestPathHelper::GetTestDataPath(name); }
    static std::string scratch(const char* name) { return TestPathHelper::GetTestScratchPath(name); }

    static TRDVolumeInfo* volumeOf(DiskImage* image)
    {
        return reinterpret_cast<TRDVolumeInfo*>(image->getTrackForCylinderAndSide(0, 0)->getSector(TRD_VOLUME_SECTOR)->data);
    }

    /// Raw bytes of every track, for "image untouched" comparisons
    static std::vector<std::vector<uint8_t>> snapshot(DiskImage* image)
    {
        std::vector<std::vector<uint8_t>> result;
        const size_t trackCount = static_cast<size_t>(image->getCylinders()) * image->getSides();
        for (size_t t = 0; t < trackCount; t++)
        {
            DiskImage::Track* track = image->getTrack(static_cast<uint8_t>(t));
            result.emplace_back(track->rawData(), track->rawData() + track->rawSize());
        }
        return result;
    }

    /// Blank DS80 TR-DOS disk, as LoaderSCL / LoaderHobeta build it
    DiskImage* blankTrdos()
    {
        DiskImage* image = new DiskImage(80, 2);
        LoaderTRD trd(_context, "");
        EXPECT_TRUE(trd.format(image));
        image->markClean();
        return image;
    }

    /// Expected sector chain content: the fixture body starting at sector n of the file
    static void expectFileOnDisk(DiskImage* image, const TRDOSDirectoryEntry& entry, const std::vector<uint8_t>& body)
    {
        ASSERT_EQ(body.size(), static_cast<size_t>(entry.SizeInSectors) * TRD_SECTORS_SIZE_BYTES);
        uint16_t locator = static_cast<uint16_t>(entry.StartTrack * TRD_SECTORS_PER_TRACK + entry.StartSector);
        for (size_t n = 0; n < entry.SizeInSectors; n++, locator++)
        {
            DiskImage::Track* track = image->getTrack(static_cast<uint8_t>(locator / TRD_SECTORS_PER_TRACK));
            DiskImage::Sector* sector = track->getSector(static_cast<uint8_t>(locator % TRD_SECTORS_PER_TRACK));
            ASSERT_NE(sector, nullptr) << "locator " << locator;
            ASSERT_EQ(sector->dataSize, TRD_SECTORS_SIZE_BYTES);
            EXPECT_TRUE(sector->isDataCRCValid()) << "locator " << locator;
            EXPECT_EQ(std::memcmp(sector->data, body.data() + n * TRD_SECTORS_SIZE_BYTES, TRD_SECTORS_SIZE_BYTES), 0)
                << "file sector " << n << " at TR-DOS locator " << locator;
        }
    }

    /// READ SECTOR through the WD1793 (MFM, DENSITY bit clear), 3-second T-state budget
    std::vector<uint8_t> readThroughController(DiskImage* image, uint8_t cyl, uint8_t side, uint8_t number)
    {
        WD1793CUT fdc(_context);
        fdc.getDrive()->insertDisk(image);
        fdc._beta128Register = WD1793CUT::BETA128_COMMAND_BITS::BETA_CMD_RESET;
        fdc._drive = 0;
        fdc.wakeUp();
        fdc._time = 1000;
        fdc.prolongFDDMotorRotation();
        fdc._trackRegister = cyl;
        fdc._selectedDrive->setTrack(cyl);
        fdc._sideUp = side != 0;
        fdc._sectorRegister = number;
        fdc._commandRegister = 0x80;
        fdc._lastDecodedCmd = WD1793::WD_CMD_READ_SECTOR;
        fdc.cmdReadSector(0x00);

        std::vector<uint8_t> read;
        for (size_t clk = 1000; clk < 1000 + 3'500'000 * 3 && fdc._state != WD1793::S_IDLE; clk += 100)
        {
            fdc._time = clk;
            fdc.process();
            if (fdc._beta128status & WD1793::DRQ) read.push_back(fdc.readDataRegister());
        }
        EXPECT_EQ(fdc._state, WD1793::S_IDLE) << "READ SECTOR did not finish within 3 seconds";
        EXPECT_FALSE(fdc._statusRegister & WD1793::WDS_NOTFOUND);
        fdc.getDrive()->ejectDisk();
        return read;
    }
};

