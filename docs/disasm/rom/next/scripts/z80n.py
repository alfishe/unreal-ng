"""Z80 / Z80N helper for the Next ROM listings: instruction length and control flow.

Same idea as the Sprinter helper (docs/disasm/rom/sprinter/scripts/z80.py), plus the Z80N
extended opcodes (all under the ED prefix, research-z80n.md of the Next design).
"""

_LEN2 = {0x06, 0x0E, 0x16, 0x1E, 0x26, 0x2E, 0x36, 0x3E,
         0x10, 0x18, 0x20, 0x28, 0x30, 0x38,
         0xC6, 0xCE, 0xD6, 0xDE, 0xE6, 0xEE, 0xF6, 0xFE,
         0xD3, 0xDB, 0xCB}
_LEN3 = {0x01, 0x11, 0x21, 0x31, 0x22, 0x2A, 0x32, 0x3A,
         0xC2, 0xC3, 0xC4, 0xCA, 0xCC, 0xCD, 0xD2, 0xD4, 0xDA, 0xDC,
         0xE2, 0xE4, 0xEA, 0xEC, 0xF2, 0xF4, 0xFA, 0xFC}
_HLMEM = {0x34, 0x35, 0x36, 0x46, 0x4E, 0x56, 0x5E, 0x66, 0x6E, 0x7E,
          0x70, 0x71, 0x72, 0x73, 0x74, 0x75, 0x77,
          0x86, 0x8E, 0x96, 0x9E, 0xA6, 0xAE, 0xB6, 0xBE}
_ED4 = {0x43, 0x4B, 0x53, 0x5B, 0x63, 0x6B, 0x73, 0x7B}
# Z80N: ED xx with 0 / 1 / 2 operand bytes
_N0 = {0x23, 0x24, 0x28, 0x29, 0x2A, 0x2B, 0x2C, 0x30, 0x31, 0x32, 0x33, 0x90, 0x93, 0x94, 0x95, 0x98,
       0xA4, 0xA5, 0xAC, 0xB4, 0xB6, 0xB7, 0xBC}
_N1 = {0x27, 0x92}
_N2 = {0x34, 0x35, 0x36, 0x8A, 0x91}

JR_COND = {0x20, 0x28, 0x30, 0x38}
JP_COND = {0xC2, 0xCA, 0xD2, 0xDA, 0xE2, 0xEA, 0xF2, 0xFA}
CALL_ANY = {0xCD, 0xC4, 0xCC, 0xD4, 0xDC, 0xE4, 0xEC, 0xF4, 0xFC}
RST = {0xC7, 0xCF, 0xD7, 0xDF, 0xE7, 0xEF, 0xF7, 0xFF}


def length(data, pos):
    b = data[pos]
    if b in (0xDD, 0xFD):
        if pos + 1 >= len(data):
            return 1
        n = data[pos + 1]
        if n in (0xDD, 0xFD, 0xED):
            return 1
        if n in (0xCB, 0x36):
            return 4
        base = 3 if n in _LEN3 else 2 if n in _LEN2 else 1
        return 1 + base + (1 if n in _HLMEM else 0)
    if b == 0xED:
        if pos + 1 >= len(data):
            return 1
        n = data[pos + 1]
        if n in _ED4 or n in _N2:
            return 4
        if n in _N1:
            return 3
        return 2
    if b in _LEN3:
        return 3
    if b in _LEN2:
        return 2
    return 1


def flow(data, pos, org=0):
    """(targets, falls_through) of the instruction at pos."""
    b = data[pos]
    here = org + pos
    if b in (0x18, 0x10) or b in JR_COND:
        off = data[pos + 1]
        return [(here + 2 + (off - 256 if off >= 128 else off)) & 0xFFFF], b != 0x18
    if b == 0xC3 or b in JP_COND or b in CALL_ANY:
        return [data[pos + 1] | (data[pos + 2] << 8)], b != 0xC3
    if b in RST:
        return [b & 0x38], True
    if b in (0xC9, 0xE9, 0x76):
        return [], False
    if b in (0xDD, 0xFD) and pos + 1 < len(data) and data[pos + 1] == 0xE9:
        return [], False
    if b == 0xED and pos + 1 < len(data):
        n = data[pos + 1]
        if n in (0x45, 0x4D, 0x55, 0x5D, 0x65, 0x6D, 0x75, 0x7D, 0x98):   # RETN / RETI / JP (C)
            return [], False
    return [], True
