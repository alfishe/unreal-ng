"""What every style shares: the SVG frame with its named layers and legend placement."""

from svgkit import Defs, text_path

LAYERS = ["case", "caps", "legends", "hints"]


class Picture:
    def __init__(self, keyboard):
        self.keyboard = keyboard
        self.defs = Defs()
        self.layers = {name: [] for name in LAYERS}

    def add(self, layer, svg):
        if svg:
            self.layers[layer].append(svg)

    def svg(self):
        w, h = self.keyboard["size"]
        groups = "\n".join(f'<g id="{name}">\n' + "\n".join(self.layers[name]) + "\n</g>" for name in LAYERS)
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w * 6:.0f}" height="{h * 6:.0f}" '
                f'viewBox="0 0 {w} {h}">\n<!-- generated by tools/poc/031-authentic-osd-keyboards/generate.py -->\n'
                f"{self.defs.svg()}\n{groups}\n</svg>\n")


def glyphs(text, x, y, size, face="sans-bold", color="#fff", anchor="middle", opacity=1.0, squeeze=1.0,
           spacing=0.0):
    d = text_path(text, x, y, size, face, anchor, spacing, squeeze)
    if not d:
        return ""
    extra = f' fill-opacity="{opacity}"' if opacity != 1 else ""
    return f'<path d="{d}" fill="{color}"{extra}/>'


def legend_origin(legend, key, face):
    """Where a legend's baseline anchor is: on the cap within @p face (the cap's top face this style draws), or on
    the case above / below the key's rectangle"""
    x, y, w, h = key.rect
    if legend.at == "cap":
        fx, fy, fw, fh = face
        return fx + legend.x * fw, fy + legend.y * fh
    if legend.at == "cell":
        return x + legend.x * w, y + legend.y * h
    if legend.at == "above":
        return x + legend.x * w, y - legend.y
    if legend.at == "below":
        return x + legend.x * w, y + h + legend.y + legend.size * 0.75
    raise ValueError(f"{key.id}: legend at {legend.at}")


def glyph_shape(glyph, x, y, size, color):
    """A legend drawn as a shape, centred on (x, y), @p size its height: `block:N` the ZX block graphic N in its
    box, `arrow:up|down|left|right` a hollow arrow"""
    kind, _, arg = glyph.partition(":")
    if kind == "block":
        s, n = size, int(arg)
        x0, y0, half = x - s / 2, y - s / 2, s / 2
        quads = [(1, x0 + half, y0), (2, x0, y0), (4, x0 + half, y0 + half), (8, x0, y0 + half)]
        parts = [f'<rect x="{qx:.3f}" y="{qy:.3f}" width="{half:.3f}" height="{half:.3f}" fill="{color}"/>'
                 for bit, qx, qy in quads if n & bit]
        parts.append(f'<rect x="{x0:.3f}" y="{y0:.3f}" width="{s:.3f}" height="{s:.3f}" fill="none" '
                     f'stroke="{color}" stroke-width="{s * 0.08:.3f}"/>')
        return "".join(parts)
    if kind == "arrow":
        unit = [(0, -0.5), (0.45, -0.02), (0.18, -0.02), (0.18, 0.5), (-0.18, 0.5), (-0.18, -0.02), (-0.45, -0.02)]
        turn = {"up": (1, 0, 0, 1), "down": (1, 0, 0, -1), "left": (0, 1, 1, 0), "right": (0, -1, -1, 0)}[arg]
        a, b, c, e = turn
        points = [(x + (a * px + b * py) * size, y + (c * px + e * py) * size) for px, py in unit]
        d = "M" + " L".join(f"{px:.3f},{py:.3f}" for px, py in points) + "Z"
        return (f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{size * 0.07:.3f}" '
                f'stroke-linejoin="round"/>')
    raise ValueError(f"glyph {glyph}")
