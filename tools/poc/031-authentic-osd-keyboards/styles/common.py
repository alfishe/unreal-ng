"""What every style shares: the SVG frame with its named layers and legend placement."""

from svgkit import Defs, rounded, text_path, text_width

LAYERS = ["case", "caps", "highlights", "legends", "hints"]
HIGHLIGHTS = 0.5  # the highlights layer's opacity unless the keyboard sets its own


class Picture:
    def __init__(self, keyboard):
        self.keyboard = keyboard
        self.defs = Defs()
        self.layers = {name: [] for name in LAYERS}

    def add(self, layer, svg, role=None):
        """@p role puts the svg in a group of its own inside the layer, `<g id="<layer>-<role>">`: the legends by role
        (main, keyword, symbol...), so an app can draw or dim one role alone"""
        if svg:
            self.layers[layer].append((role, svg))

    def body(self, layer):
        loose, roles = [], {}
        for role, svg in self.layers[layer]:
            (roles.setdefault(role, []) if role else loose).append(svg)
        return "\n".join(loose + [f'<g id="{layer}-{role}">\n' + "\n".join(items) + "\n</g>"
                                  for role, items in roles.items()])

    def svg(self):
        w, h = self.keyboard["size"]
        opacity = {"highlights": self.keyboard.get("highlights", HIGHLIGHTS), **getattr(self, "opacity", {})}
        groups = "\n".join(f'<g id="{name}"' + (f' opacity="{opacity[name]}"' if opacity.get(name, 1) != 1 else "") +
                           ">\n" + self.body(name) + "\n</g>" for name in LAYERS)
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w * 6:.0f}" height="{h * 6:.0f}" '
                f'viewBox="0 0 {w} {h}">\n<!-- generated by tools/poc/031-authentic-osd-keyboards/generate.py -->\n'
                f"{self.defs.svg()}\n{groups}\n</svg>\n")


def glyphs(text, x, y, size, face="sans-bold", color="#fff", anchor="middle", opacity=1.0, squeeze=1.0,
           spacing=0.0):
    d = text_path(text, x, y, size, face, anchor, spacing, squeeze)
    if not d:
        return ""
    extra = f' fill-opacity="{opacity}"' if opacity != 1 else ""
    return f'<path d="{d}" fill="{color}"{extra}/>'


def legend_origin(legend, key, face):
    """Where a legend's baseline anchor is: on the cap within @p face (the cap's top face this style draws), or on
    the case above / below the key's rectangle"""
    x, y, w, h = key.rect
    if legend.at == "cap":
        fx, fy, fw, fh = face
        return fx + legend.x * fw, fy + legend.y * fh
    if legend.at == "cell":
        return x + legend.x * w, y + legend.y * h
    if legend.at == "above":
        return x + legend.x * w, y - legend.y
    if legend.at == "below":
        return x + legend.x * w, y + h + legend.y + legend.size * 0.75
    raise ValueError(f"{key.id}: legend at {legend.at}")


def glyph_shape(glyph, x, y, size, color):
    """A legend drawn as a shape, centred on (x, y), @p size its height: `block:N` the ZX block graphic N in its
    box (`block:N:paper` the 48K's print: the paper quadrants in @p color, no box), `arrow:up|down|left|right` a hollow
    arrow, `chevron:dir` / `chevron2:dir` an open single / double chevron (the Amstrad's cursor keys and tape
    buttons), `dot` a filled disc, `eject` a hollow roof over a bar, `pause` two bars, `hook` the return hook ┘ with
    its corner at (x, y); `tri:dir` / `tri2:dir` a filled single / double triangle, `eject:fill`, `pause:fill` the
    filled ones (the +2A's tape symbols printed on the case); `sticker:zx` a Soviet key sticker @p size square,
    dark, its top and bottom bands in @p color, `sticker:plain` one all in @p color, `enter` the hollow return arrow, `box` a hollow square (the Quorum's
    boxed E and G, the letter is a legend of its own), `speaker` a hollow loudspeaker, `tab` the XT's ⇤ ⇥, `win` the four panes of a PC's
    Windows key, `menu` its context-menu key"""
    kind, _, arg = glyph.partition(":")
    if kind == "block":
        arg, _, polarity = arg.partition(":")
        s, n = size, int(arg)
        if polarity == "paper":
            x0, y0, half = x - s / 2, y - s / 2, s / 2
            quads = [(1, x0 + half, y0), (2, x0, y0), (4, x0 + half, y0 + half), (8, x0, y0 + half)]
            return "".join(f'<rect x="{qx:.3f}" y="{qy:.3f}" width="{half:.3f}" height="{half:.3f}" fill="{color}"/>'
                           for bit, qx, qy in quads if not n & bit)
        x0, y0, half = x - s / 2, y - s / 2, s / 2
        quads = [(1, x0 + half, y0), (2, x0, y0), (4, x0 + half, y0 + half), (8, x0, y0 + half)]
        parts = [f'<rect x="{qx:.3f}" y="{qy:.3f}" width="{half:.3f}" height="{half:.3f}" fill="{color}"/>'
                 for bit, qx, qy in quads if n & bit]
        parts.append(f'<rect x="{x0:.3f}" y="{y0:.3f}" width="{s:.3f}" height="{s:.3f}" fill="none" '
                     f'stroke="{color}" stroke-width="{s * 0.08:.3f}"/>')
        return "".join(parts)
    if kind == "arrow":
        unit = [(0, -0.5), (0.45, -0.02), (0.18, -0.02), (0.18, 0.5), (-0.18, 0.5), (-0.18, -0.02), (-0.45, -0.02)]
        turn = {"up": (1, 0, 0, 1), "down": (1, 0, 0, -1), "left": (0, 1, 1, 0), "right": (0, -1, -1, 0)}[arg]
        a, b, c, e = turn
        points = [(x + (a * px + b * py) * size, y + (c * px + e * py) * size) for px, py in unit]
        d = "M" + " L".join(f"{px:.3f},{py:.3f}" for px, py in points) + "Z"
        return (f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{size * 0.07:.3f}" '
                f'stroke-linejoin="round"/>')
    stroke = f'fill="none" stroke="{color}" stroke-width="{size * 0.11:.3f}" stroke-linecap="round" ' \
             f'stroke-linejoin="round"'
    if kind in ("chevron", "chevron2"):  # drawn pointing right, then turned
        unit = [[(-0.22, -0.5), (0.22, 0), (-0.22, 0.5)]]
        if kind == "chevron2":
            unit = [[(px - 0.2, py) for px, py in unit[0]], [(px + 0.2, py) for px, py in unit[0]]]
        a, b, c, e = {"right": (1, 0, 0, 1), "left": (-1, 0, 0, 1), "up": (0, 1, -1, 0), "down": (0, 1, 1, 0)}[arg]
        return "".join('<path d="M' + " L".join(f"{x + (a * px + b * py) * size:.3f},{y + (c * px + e * py) * size:.3f}"
                                                 for px, py in line) + f'" {stroke}/>' for line in unit)
    if kind == "enter":  # the hollow return arrow ↲: down the right, left along the bottom, the head at its end
        s, t = size, size * 0.11
        points = [(0.3, -0.5), (0.42, -0.5), (0.42, 0.28), (-0.12, 0.28), (-0.12, 0.42), (-0.42, 0.2), (-0.12, -0.02),
                  (-0.12, 0.12), (0.3, 0.12)]
        d = "M" + " L".join(f"{x + px * s:.3f},{y + py * s:.3f}" for px, py in points) + "Z"
        return f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{t * 0.6:.3f}" stroke-linejoin="miter"/>'
    if kind == "sticker":
        h = size / 2
        parts = [f'<path d="{rounded(x - h, y - h, size, size, size * 0.1)}" '
                 f'fill="{color if arg == "plain" else "#242528"}"/>']
        if arg == "zx":  # the bands: rounded strips inset in the sticker's top and bottom
            band, inset = size * 0.2, size * 0.06
            for by in (y - h + inset * 0.6, y + h - inset * 0.6 - band):
                parts.append(f'<path d="{rounded(x - h + inset, by, size - 2 * inset, band, band * 0.45)}" '
                             f'fill="{color}"/>')
        parts.append(f'<path d="{rounded(x - h, y - h, size, size, size * 0.1)}" fill="none" stroke="#9a9a9a" '
                     f'stroke-width="{size * 0.012:.3f}" stroke-opacity="0.6"/>')
        return "".join(parts)
    if kind in ("tri", "tri2"):  # drawn pointing right, then turned
        unit = [[(-0.3, -0.38), (0.3, 0), (-0.3, 0.38)]]
        if kind == "tri2":
            unit = [[(px - 0.28, py) for px, py in unit[0]], [(px + 0.28, py) for px, py in unit[0]]]
        a, b, c, e = {"right": (1, 0, 0, 1), "left": (-1, 0, 0, 1), "up": (0, 1, -1, 0), "down": (0, 1, 1, 0)}[arg]
        return "".join('<path d="M' + " L".join(f"{x + (a * px + b * py) * size:.3f},{y + (c * px + e * py) * size:.3f}"
                                                 for px, py in tri) + f'Z" fill="{color}"/>' for tri in unit)
    if kind == "dot":
        return f'<circle cx="{x:.3f}" cy="{y:.3f}" r="{size / 2:.3f}" fill="{color}"/>'
    if kind == "eject" and arg == "fill":
        s = size
        return (f'<path d="M{x - 0.42 * s:.3f},{y + 0.08 * s:.3f} L{x:.3f},{y - 0.38 * s:.3f} L{x + 0.42 * s:.3f},'
                f'{y + 0.08 * s:.3f}Z" fill="{color}"/>'
                f'<rect x="{x - 0.42 * s:.3f}" y="{y + 0.2 * s:.3f}" width="{0.84 * s:.3f}" height="{0.16 * s:.3f}" '
                f'fill="{color}"/>')
    if kind == "pause" and arg == "fill":
        return "".join(f'<rect x="{x + dx * size:.3f}" y="{y - 0.38 * size:.3f}" width="{0.16 * size:.3f}" '
                       f'height="{0.76 * size:.3f}" fill="{color}"/>' for dx in (-0.24, 0.08))
    if kind == "eject":
        s = size
        return (f'<path d="M{x - 0.5 * s:.3f},{y + 0.05 * s:.3f} L{x:.3f},{y - 0.35 * s:.3f} L{x + 0.5 * s:.3f},'
                f'{y + 0.05 * s:.3f}Z" {stroke}/>'
                f'<path d="{rounded(x - 0.5 * s, y + 0.22 * s, s, 0.18 * s, 0.05 * s)}" {stroke}/>')
    if kind == "pause":
        return "".join(f'<path d="M{x + dx * size:.3f},{y - 0.4 * size:.3f} V{y + 0.4 * size:.3f}" {stroke}/>'
                       for dx in (-0.15, 0.15))
    if kind == "box":
        h = size / 2
        return (f'<rect x="{x - h:.3f}" y="{y - h:.3f}" width="{size:.3f}" height="{size:.3f}" fill="none" '
                f'stroke="{color}" stroke-width="{size * 0.07:.3f}"/>')
    if kind == "speaker":  # the magnet's box and the cone opening to the right
        s = size
        points = [(-0.45, -0.18), (-0.15, -0.18), (0.25, -0.5), (0.25, 0.5), (-0.15, 0.18), (-0.45, 0.18)]
        d = "M" + " L".join(f"{x + px * s:.3f},{y + py * s:.3f}" for px, py in points) + "Z"
        return f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{s * 0.07:.3f}" stroke-linejoin="round"/>'
    if kind == "tab":  # the XT's Tab: ⇤ over ⇥, a bar at each arrow's head
        s, t = size, size * 0.07
        parts = []
        for dy, sign in ((-0.2, -1), (0.2, 1)):
            yy, tip = y + dy * s, x + sign * 0.4 * s
            parts.append(f'<path d="M{x - sign * 0.4 * s:.3f},{yy:.3f} H{tip:.3f} M{tip - sign * 0.15 * s:.3f},'
                         f'{yy - 0.1 * s:.3f} L{tip:.3f},{yy:.3f} L{tip - sign * 0.15 * s:.3f},{yy + 0.1 * s:.3f} '
                         f'M{tip:.3f},{yy - 0.13 * s:.3f} V{yy + 0.13 * s:.3f}" fill="none" stroke="{color}" '
                         f'stroke-width="{t:.3f}"/>')
        return "".join(parts)
    if kind == "win":  # the Windows key's four panes, a little apart
        h, g = size * 0.44, size * 0.12
        return "".join(f'<rect x="{x + dx:.3f}" y="{y + dy:.3f}" width="{h:.3f}" height="{h:.3f}" fill="{color}"/>'
                       for dx in (-h - g / 2, g / 2) for dy in (-h - g / 2, g / 2))
    if kind == "menu":  # the context-menu key: a page with three lines and an arrow head over its corner
        w, h = size * 0.7, size
        lines = "".join(f'<path d="M{x - w * 0.3:.3f},{y + dy * h:.3f} H{x + w * 0.3:.3f}" {stroke}/>'
                        for dy in (-0.22, 0.0, 0.22))
        return (f'<path d="{rounded(x - w / 2, y - h / 2, w, h, size * 0.06)}" fill="none" stroke="{color}" '
                f'stroke-width="{size * 0.07:.3f}"/>' + lines)
    if kind == "hook":
        return (f'<path d="M{x - 1.0 * size:.3f},{y:.3f} H{x:.3f} V{y - size:.3f}" fill="none" stroke="{color}" '
                f'stroke-width="{size * 0.07:.3f}" stroke-linejoin="miter"/>')
    raise ValueError(f"glyph {glyph}")


def luminance(color):
    """0 for black, 1 for white"""
    color = color.lstrip("#")
    if len(color) == 3:
        color = "".join(c * 2 for c in color)
    r, g, b = (int(color[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def legends(pic, key, face):
    """The key's legends into the `legends` layer, each in its role's group; @p face the cap's top face as the style
    draws it (the legends at `cap` are placed in it)"""
    for legend in key.legends:
        lx, ly = legend_origin(legend, key, face)
        role = legend.role
        if legend.glyph:
            pic.add("legends", glyph_shape(legend.glyph, lx, ly, legend.size, legend.color), role)
            continue
        if legend.inverse:
            text = text_width(legend.text, legend.size, legend.face) * legend.squeeze
            pad = legend.size * 0.3
            width = text + 2 * pad
            left = {"start": lx - pad, "middle": lx - width / 2, "end": lx - text - pad}[legend.anchor]
            pic.add("legends", f'<rect x="{left:.3f}" y="{ly - legend.size * 0.95:.3f}" '
                               f'width="{width:.3f}" height="{legend.size * 1.2:.3f}" fill="{legend.color}"/>', role)
            paper = "#141517" if luminance(legend.color) > 0.5 else "#f2f2f2"  # the box's text: its opposite
            pic.add("legends", glyphs(legend.text, lx, ly, legend.size, legend.face, paper, legend.anchor,
                                      squeeze=legend.squeeze), role)
            continue
        if legend.swatch:
            pic.add("legends", f'<rect x="{lx - legend.size:.3f}" y="{ly - legend.size * 0.8:.3f}" '
                               f'width="{legend.size * 2:.3f}" height="{legend.size:.3f}" fill="{legend.swatch}"/>', role)
        pic.add("legends", glyphs(legend.text, lx, ly, legend.size, legend.face, legend.color, legend.anchor,
                                  squeeze=legend.squeeze), role)
