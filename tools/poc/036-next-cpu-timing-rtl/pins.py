#!/usr/bin/env python3
"""POC 036: the RTL's instruction durations around the points that matter, as the C++ table of NextRtlTiming_Test (the pinned cases).

    pins.py <out dir of run.sh> <program>-<48|128|p3> ... > core/tests/emulator/machines/next/nextrtltiming_pins.h

Each case: the program's body (gen.py), its run address, NR #03, the T after the INT the body starts at in this emulator (the RTL's less
2, compare.py), and windows of consecutive instruction durations in T: the first paper lines (contention), the DMA transfers, the
NR #08 switches. A duration is from the end of one opcode fetch to the next less their fixed offset, so a fetch's own wait counts
in the instruction it fetches on either side.
"""
import os
import sys

import compare

NR03 = {"48": 0x91, "128": 0xA2, "p3": 0xB3}
RUN_AT = {"mix5": 0x6000, "nreg5": 0x6000}


def windows_of(program, inst):
    """(first instruction, count) of each window"""
    pcs = [a for c, a, vc, hc in inst]
    t = [c for c, a, vc, hc in inst]

    def at_pc(pc, before, count, nth=0):
        hits = [k for k, a in enumerate(pcs) if a == pc and (k == 0 or pcs[k - 1] != pc)]
        return (hits[nth] - before, count)

    if program == "dmapaper":
        return [at_pc(0x8118, 2, 6), at_pc(0x8128, 2, 6)]  # the NOP after the OTIR that enables each block
    if program.startswith("dma") or program.startswith("zdma"):
        return [at_pc(0x8112, 2, 24)]
    if program == "nr08":
        return [at_pc(0x810F, 4, 24), at_pc(0x8129, 4, 30)]
    first = next(k for k, c in enumerate(t) if (c - t[0]) / 8 >= 14300 - 70)
    return [(first, 160)]


def main():
    out = sys.argv[1]
    cases = []
    for run in sys.argv[2:]:
        name = "rtl-%s.txt" % run
        program, timing = run.rsplit("-", 1)
        run_at = RUN_AT.get(program, 0x8100)
        ints, inst, ports = compare.rtl_events(os.path.join(out, name))
        ref, i0 = compare.body_origin(ints, inst, run_at)
        body = inst[i0:]
        assert (body[0][0] - ref) % 8 == 0, run
        start = (body[0][0] - ref) // 8 - 2
        image = open(os.path.join(out, "roms", program + ".bin"), "rb").read()
        code = image[0x100:0x200].rstrip(b"\0")
        wins = []
        for first, count in windows_of(program, body):
            d = [(body[k + 1][0] - body[k][0]) // 8 for k in range(first, first + count)]
            assert all((body[k + 1][0] - body[k][0]) % 8 == 0 for k in range(first, first + count)), run
            wins.append((first, d))
        cases.append((program + "-" + timing, NR03[timing], run_at, start, code, wins))
    print("// Generated by tools/poc/036-next-cpu-timing-rtl/pins.py from the RTL traces of POC 036 (the zxnext core in GHDL): do not edit")
    print("#pragma once")
    print()
    print("#include <cstdint>")
    print("#include <vector>")
    print()
    print("struct NextRtlWindow")
    print("{")
    print("    uint32_t first;  ///< the instruction of the body the window starts at")
    print("    std::vector<uint16_t> durations;")
    print("};")
    print()
    print("struct NextRtlCase")
    print("{")
    print("    const char* name;")
    print("    uint8_t nr03;")
    print("    uint16_t runAt;")
    print("    uint32_t startT;  ///< after the INT, in this emulator's count")
    print("    std::vector<uint8_t> body;")
    print("    std::vector<NextRtlWindow> windows;")
    print("};")
    print()
    print("inline const std::vector<NextRtlCase>& NextRtlCases()")
    print("{")
    print("    static const std::vector<NextRtlCase> cases = {")
    for name, nr03, run_at, start, code, wins in cases:
        print('        {"%s", 0x%02X, 0x%04X, %d,' % (name, nr03, run_at, start))
        hexes = ["0x%02X" % b for b in code]
        print("         {")
        for i in range(0, len(hexes), 20):
            print("             " + ", ".join(hexes[i:i + 20]) + ",")
        print("         },")
        print("         {")
        for first, d in wins:
            print("             {%d, {%s}}," % (first, ", ".join(str(x) for x in d)))
        print("         }},")
    print("    };")
    print("    return cases;")
    print("}")


if __name__ == "__main__":
    main()
