// poc_codec_latency.cpp — C++ codec comparison for the TTD workload.
//
// This PoC measures candidate codecs (zstd, lz4, brotli, snappy, FastLZ,
// zlib) against TWO classes of input:
//
//   1. REAL buffers extracted from an actual .ttd recording
//      (tools/poc/01-ttd-compression/cpp/real_buffers.bin — produced by
//      extract_real_buffers.py from testdata/ttd/active_demo.ttd, which is a
//      real recording made through the emulator API).
//      These are the exact 4 KB buffers the TTD codec hands to the
//      compressor in production: raw page snapshots (REAL_full) and
//      XOR-delta buffers (REAL_xor, the dominant workload).
//
//   2. SYNTHETIC workloads for shape-comparison purposes: random 4 KB,
//      synthetic 5% XOR-delta, all-zero. These are kept only as reference
//      points to demonstrate why conclusions drawn from synthetic data
//      alone are unreliable.
//
// Methodology:
//   - Each codec x workload pair is registered as a Google Benchmark
//     BENCHMARK_CAPTURE.
//   - Per iteration, the benchmark encodes every buffer in the workload
//     once and decodes it once, timing each encode/decode call with
//     std::chrono::steady_clock.
//   - p50/p95/p99 latency, throughput (MB/s), ratio (encoded/raw),
//     and distance to the Shannon entropy floor are reported as
//     UserCounters.

