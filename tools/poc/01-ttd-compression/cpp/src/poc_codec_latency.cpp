#ifdef SNAPPY_FOUND
Codec make_snappy() {
    Codec c;
    c.name = "snappy";
    c.encode = [](const uint8_t* s, size_t n, uint8_t* d, size_t /*cap*/) -> size_t {
        size_t out_n = 0;
        snappy::RawCompress(reinterpret_cast<const char*>(s), n,
                            reinterpret_cast<char*>(d), &out_n);
        return out_n;
    };
    c.decode = [](const uint8_t* s, size_t n, uint8_t* d, size_t /*cap*/) -> size_t {
        size_t out_n = 0;
        if (!snappy::GetUncompressedLength(reinterpret_cast<const char*>(s), n, &out_n)) return 0;
        if (!snappy::RawUncompress(reinterpret_cast<const char*>(s), n,
                                    reinterpret_cast<char*>(d))) return 0;
        return out_n;
    };
    c.bound = [](size_t n) { return snappy::MaxCompressedLength(n); };
    return c;
}
#endif

#ifdef BROTLI_FOUND
Codec make_brotli(int level) {
    Codec c;
    c.name = "brotli-" + std::to_string(level);
    c.encode = [level](const uint8_t* s, size_t n, uint8_t* d, size_t cap) -> size_t {
        size_t out_n = cap;
        if (BROTLI_TRUE != BrotliEncoderCompress(
                level, BROTLI_DEFAULT_WINDOW, BROTLI_DEFAULT_MODE,
                n, s, &out_n, d)) return 0;
        return out_n;
    };
    c.decode = [](const uint8_t* s, size_t n, uint8_t* d, size_t cap) -> size_t {
        size_t out_n = cap;
        if (BROTLI_DECODER_RESULT_SUCCESS != BrotliDecoderDecompress(
                n, s, &out_n, d)) return 0;
        return out_n;
    };
    c.bound = [](size_t n) { return n + (n >> 1) + 64; };
    return c;
}
#endif

Codec make_fastlz(int level) {
    Codec c;
    c.name = "fastlz-" + std::to_string(level);
    c.encode = [level](const uint8_t* s, size_t n, uint8_t* d, size_t cap) -> size_t {
        int r = fastlz_compress_level(level, s, static_cast<int>(n), d);
        return (r > 0 && static_cast<size_t>(r) <= cap) ? static_cast<size_t>(r) : 0;
    };
    c.decode = [](const uint8_t* s, size_t n, uint8_t* d, size_t cap) -> size_t {
        int r = fastlz_decompress(s, static_cast<int>(n), d, static_cast<int>(cap));
        return r > 0 ? static_cast<size_t>(r) : 0;
    };
    c.bound = [](size_t n) { return n + n / 100 + 8; };
    return c;
}

#ifdef ZLIB_FOUND
Codec make_zlib(int level) {
    Codec c;
    c.name = "zlib-" + std::to_string(level);
    c.encode = [level](const uint8_t* s, size_t n, uint8_t* d, size_t cap) -> size_t {
        uLongf out_n = cap;
        if (Z_OK != compress2(d, &out_n, s, static_cast<uLong>(n), level)) return 0;
        return out_n;
    };
    c.decode = [](const uint8_t* s, size_t n, uint8_t* d, size_t cap) -> size_t {
        uLongf out_n = cap;
        if (Z_OK != uncompress(d, &out_n, s, static_cast<uLong>(n))) return 0;
        return out_n;
    };
    c.bound = [](size_t n) { return compressBound(static_cast<uLong>(n)); };
    return c;
}
#endif

