"""The picture being built: views placed on the 2048 x 1536 design canvas, the four layers, the hotspots.

A device module draws in millimetres of the device inside a `View` (origin at the device's centre, x right, y down);
the view places it on the canvas with one transform. Hotspots are computed through the same transform, so a hotspot
sits exactly over what was drawn for it.
"""

from svgkit import Defs, num

W, H = 2048, 1536
LAYERS = ("shoulders", "case", "controls", "highlights", "legends")  # shoulders: the parts behind the shell
PX_PER_MM = 8.6  # one scale for every pad: the widest (DualSense, 160 mm) is 1376 px of the 1600 px device area


class View:
    def __init__(self, picture, name, ox, oy, scale):
        self.picture = picture
        self.name = name
        self.ox, self.oy, self.scale = ox, oy, scale
        self.parts = {layer: [] for layer in LAYERS}
        self.defs = picture.defs
        # Control names as the device's driver reports them, when they differ from what a shared drawing names
        # (a Joy-Con held sideways: its arrows are the face buttons); "rstick" renames rstick.x / .y / .click
        self.rename = {}

    def named(self, control):
        if control is None or control in self.rename:
            return self.rename.get(control, control)
        head, dot, tail = control.partition(".")
        return self.rename[head] + dot + tail if dot and head in self.rename else control

    def canvas(self, x, y):
        return self.ox + x * self.scale, self.oy + y * self.scale

    def add(self, layer, svg, control=None):
        """@p svg into @p layer; with @p control inside that control's group (`control-<name>` or `legend-<name>`)"""
        self.parts[layer].append((self.named(control), svg))

    def spot(self, control, label, shape, side, anchor=None, analog=None, group=None, quiet=False):
        """A hotspot: @p shape ("circle", cx, cy, r) or ("rect", x, y, w, h) in mm of this view"""
        control = self.named(control)
        group = self.named(group)
        if shape[0] == "circle":
            _, cx, cy, r = shape
            x, y = self.canvas(cx, cy)
            canvas_shape = {"circle": [round(x), round(y), round(r * self.scale)]}
            centre = (x, y)
        else:
            _, x, y, w, h = shape
            x0, y0 = self.canvas(x, y)
            canvas_shape = {"rect": [round(x0), round(y0), round(w * self.scale), round(h * self.scale)]}
            centre = (x0 + w * self.scale / 2, y0 + h * self.scale / 2)
        if anchor is not None:
            centre = self.canvas(*anchor)
        entry = {"control": control, "label": label, "shape": canvas_shape,
                 "anchor": [round(centre[0]), round(centre[1])], "callout": side}
        if analog:
            analog = dict(analog)
            if "pair" in analog:
                analog["pair"] = self.named(analog["pair"])
            if "radius" in analog:
                analog["radius"] = round(analog["radius"] * self.scale)
            entry["analog"] = analog
        if group:
            entry["group"] = group
        if quiet:
            entry["quiet"] = True
        self.picture.spots.append(entry)

    def svg(self, layer):
        out, open_control = [], None
        for control, svg in self.parts[layer]:
            if control != open_control:
                if open_control is not None:
                    out.append("</g>")
                if control is not None:
                    prefix = {"controls": "control", "shoulders": "control", "legends": "legend"}.get(layer, layer)
                    out.append(f'<g id="{prefix}-{control}">')
                open_control = control
            out.append(svg)
        if open_control is not None:
            out.append("</g>")
        if not out:
            return ""
        return (f'<g transform="translate({num(self.ox)} {num(self.oy)}) scale({num(self.scale)})">\n'
                + "\n".join(out) + "\n</g>")


class Picture:
    def __init__(self, family, title):
        self.family = family
        self.title = title
        self.defs = Defs()
        self.views = []
        self.spots = []
        self.sources = []

    def view(self, name, ox=W / 2, oy=H / 2, scale=PX_PER_MM):
        view = View(self, name, ox, oy, scale)
        self.views.append(view)
        return view

    def svg(self, generator):
        body = []
        for layer in LAYERS:
            inner = "\n".join(s for s in (v.svg(layer) for v in self.views) if s)
            body.append(f'<g id="{layer}">\n{inner}\n</g>')
        return (f'<svg xmlns="http://www.w3.org/2000/svg" version="1.2" baseProfile="tiny" width="{W}" height="{H}" '
                f'viewBox="0 0 {W} {H}">\n'
                f"<!-- {self.title}: generated by {generator}, do not edit -->\n"
                + self.defs.svg() + "\n" + "\n".join(body) + "\n</svg>\n")
