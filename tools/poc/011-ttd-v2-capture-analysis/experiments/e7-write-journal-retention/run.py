#!/usr/bin/env python3
"""Experiment E7: run the retention model on the recorded sessions and write results.md.

Inputs (record-sessions.sh, then the TTDE7 benchmark):
- <repo>/scratch/ttd-experiments/e7/<length>/ttd-bench-v1-<case>.ttd
- <repo>/scratch/ttd-experiments/e7/<length>/<timings>.json: core-benchmarks
  run with UNREAL_TTD_E7_DIR=<that folder> --benchmark_filter=TTDE7/ (the
  measured walk and regeneration costs, and the exactness check)

Usage: run.py [timings file name]   (default e7.json; e7-loaded.json when that is all there is)
"""

from __future__ import annotations

import glob
import json
import os
import sys

import numpy as np

import model as m

E7 = os.path.join(m.ROOT, "scratch", "ttd-experiments", "e7")
OUT = os.path.join(m.HERE, "results.md")
CLASSES = {"A": "last frame", "B": "1-60 s", "C": "> 60 s / never"}


def timings(folder: str, name: str):
    path = os.path.join(folder, name)
    if not os.path.exists(path):
        path = os.path.join(folder, "e7-loaded.json")
    rows = {}
    with open(path) as f:
        data = json.load(f)
    for b in data["benchmarks"]:
        if not b.get("error_occurred"):
            rows[b["name"].split("/iterations")[0].replace("TTDE7/", "")] = b
    return rows, os.path.basename(path), data["context"]


def case_of(path: str) -> str:
    base = os.path.basename(path)[len("ttd-bench-v1-"):-len(".ttd")]
    config, workload = base.rsplit("_", 1)
    return config.replace("_", "+") + "/" + workload


def mb(x: float) -> str:
    return f"{x / 1e6:.2f}"


def main():
    name = sys.argv[1] if len(sys.argv) > 1 else "e7.json"
    lines = ["# E7 results", "", "Generated by `run.py`; method and conclusions: [README.md](README.md).", ""]
    exact_rows, cost_rows, byte_rows, lat_rows = [], [], [], []
    summary = {}   # policy -> list of (p99 ms, memory MB/min, file MB/min)
    sources = set()
    for length in ("1min", "5min"):
        folder = os.path.join(E7, length)
        if not os.path.isdir(folder):
            continue
        t, source, context = timings(folder, name)
        sources.add(f"{length}: {source} (load {context.get('load_avg', '?')})")
        for path in sorted(glob.glob(os.path.join(folder, "ttd-bench-v1-*.ttd"))):
            case = case_of(path)
            b = t.get(case)
            if b is None:
                continue
            j = m.load(path)
            blocks = m.encode_blocks(j)
            idx = m.Index(j)
            queries = m.make_queries(j, idx, np.random.default_rng(m.SEED))
            results = m.evaluate(j, blocks, queries)
            minutes = j.frames / (60 * m.FRAMES_PER_SECOND)
            label = f"{case} ({length})"
            walk_us = b["e7_walk_ns_per_frame"] / 1000.0
            regen_us = b["e7_regen_us_p50"]
            counts = {c: sum(1 for q in queries if q.cls == c) for c in CLASSES}
            exact_rows.append(f"| {label} | {int(b['e7_regen_frames'])} | {b['e7_regen_writes_per_frame']:.0f} | "
                              f"{int(b['e7_regen_mismatch_frames'])} | {int(b['e7_regen_refused_frames'])} |")
            cost_rows.append(f"| {label} | {b['e7_regen_us_p50'] / 1000:.2f} | {b['e7_regen_us_p99'] / 1000:.2f} | "
                             f"{walk_us:.2f} | {j.frames * walk_us / 1000:.0f} |")
            whole = results[0].memory_bytes
            byte_rows.append(f"| {label} | {mb(j.v1_compressed / minutes)} | "
                             + " | ".join(f"{mb(r.memory_bytes / minutes)} / {mb(r.file_bytes / minutes)}" for r in results)
                             + " |")
            cells = []
            for r in results:
                lat = np.array(r.walked) * walk_us + np.array(r.replayed) * regen_us   # microseconds
                p50, p99 = np.percentile(lat, 50) / 1000, np.percentile(lat, 99) / 1000
                by_class = {c: np.percentile(v, 99) / 1000 for c in CLASSES
                            if (v := [x for x, q in zip(lat, queries) if q.cls == c])}
                cells.append(f"{p50:.1f} / {p99:.1f}")
                summary.setdefault(r.name, []).append((p99, max(by_class.values()), r.memory_bytes / minutes,
                                                       r.file_bytes / minutes, r.hits / len(queries)))
            lat_rows.append(f"| {label} | {counts['A']} / {counts['B']} / {counts['C']} | " + " | ".join(cells) + " |")
            print(label, "done", flush=True)
            del j, blocks, idx
    policies = [r.name for r in results]

    lines += ["Timings: " + "; ".join(sorted(sources)) + ".", ""]
    lines += ["## Exactness", "",
              "Each sampled frame replayed with every memory write collected "
              "(`TimeTravelManager::RegenerateFrameWrites`) against the journal's records of that frame.", "",
              "| Session | Frames replayed | Writes per frame | Frames that differ | Frames refused (v1 marker) |",
              "|---|---|---|---|---|"] + exact_rows + [""]
    lines += ["## Measured costs", "",
              "| Session | Regenerate a frame, ms p50 | p99 | Coverage walk, µs per frame | Walk of the whole session, ms |",
              "|---|---|---|---|---|"] + cost_rows + [""]
    lines += ["## Bytes per minute of history, MB (memory / file)", "",
              "v1: the journal section v1 writes (memory and port records, its record format). "
              "The policies store memory writes only, in the engine's format.", "",
              "| Session | v1 file | " + " | ".join(policies) + " |",
              "|---|---|" + "---|" * len(policies)] + byte_rows + [""]
    lines += ["## Find-last latency, ms (p50 / p99 over 1,000 queries)", "",
              "A query the kept journal answers costs microseconds (0 here). Otherwise: frames walked x the walk "
              "cost + frames replayed (at most one) x the regeneration cost p50.", "",
              "| Session | Queries A / B / C | " + " | ".join(policies) + " |",
              "|---|---|" + "---|" * len(policies)] + lat_rows + [""]
    lines += ["## Summary over the sessions", "",
              "| Policy | Worst p99, ms | Worst class p99, ms | Memory MB/min, max | File MB/min, max | Answered from the journal, min |",
              "|---|---|---|---|---|---|"]
    for p in policies:
        rows = summary[p]
        lines.append(f"| {p} | {max(r[0] for r in rows):.1f} | {max(r[1] for r in rows):.1f} | "
                     f"{max(r[2] for r in rows) / 1e6:.2f} | {max(r[3] for r in rows) / 1e6:.2f} | "
                     f"{min(r[4] for r in rows) * 100:.0f}% |")
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
