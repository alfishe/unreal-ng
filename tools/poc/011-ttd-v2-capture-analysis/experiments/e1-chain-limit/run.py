"""E1 - chain length limit per piece vs the v1 key frame.

Replays the real change history of every input session under three storage
policies and reports, per policy: stored bytes per frame, Full stores per frame
(the spike), and the decode work a full restore needs (sum over pieces of the
chain links to walk). Writes results.md next to this file.

Run: python3 run.py   (after ../common/record-datasets.sh)
"""

from __future__ import annotations

import os
import sys
from dataclasses import dataclass

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "common"))
import datasets  # noqa: E402
import piecestats as ps  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
KS = [16, 32, 50, 64, 100]


@dataclass
class Policy:
    name: str
    kind: str          # "v1" | "piece"
    k: int = 50        # v1: key-frame interval; piece: chain length limit (links < k)
    stagger: bool = False


POLICIES = [Policy("v1 key frame /50", "v1", 50)] + [
    Policy(f"limit K={k}" + (" staggered" if s else ""), "piece", k, s) for k in KS for s in (False, True)]


def simulate(rs: ps.RegionStats, pol: Policy):
    n = rs.pieces
    base = rs.key_full[0]
    nonzero = base > 0
    depth = np.zeros(n, np.int64)
    # Per-piece limit. Staggered: each piece gets its own limit in [K/2, K], so
    # pieces that change every frame since the same baseline reach their limit
    # on different frames instead of all at once (no fake depth is added: every
    # chain is a real chain)
    limit = np.full(n, pol.k, np.int64)
    if pol.kind == "piece" and pol.stagger:
        half = max(1, pol.k // 2)
        limit = pol.k - (np.arange(n, dtype=np.int64) * 7) % (pol.k - half + 1)
    changes = rs.changes_at()
    idx = {}
    order = np.argsort(rs.change_cp, kind="stable")
    for row in order:
        idx.setdefault(int(rs.change_cp[row]), []).append(row)

    bytes_per_cp = np.zeros(rs.checkpoints, np.int64)
    full_per_cp = np.zeros(rs.checkpoints, np.int64)
    forced_per_cp = np.zeros(rs.checkpoints, np.int64)   # Full stores the policy forced
    links_per_cp = np.zeros(rs.checkpoints, np.int64)
    bytes_per_cp[0] = int(base.sum())
    full_per_cp[0] = int(nonzero.sum())
    links_per_cp[0] = int((depth[nonzero] + 1).sum())
    max_depth = 0

    for i in range(1, rs.checkpoints):
        rows = idx.get(i, [])
        if pol.kind == "v1" and i % pol.k == 0 and i in rs.key_full:
            # key frame: every non-zero piece stored again in full, chains reset
            sizes = rs.key_full[i]
            for r in rows:
                nonzero[rs.change_piece[r]] = rs.change_full[r] > 0
            bytes_per_cp[i] = int(sizes[nonzero].sum())
            full_per_cp[i] = int(nonzero.sum())
            forced_per_cp[i] = int(nonzero.sum()) - len(rows)
            depth[:] = 0
        else:
            b = f = forced_n = 0
            for r in rows:
                j = int(rs.change_piece[r])
                xs, fs = int(rs.change_xor[r]), int(rs.change_full[r])
                nonzero[j] = fs > 0
                if fs == 0:                         # all-zero piece: Zero, no chain
                    depth[j] = 0
                    continue
                forced = pol.kind == "piece" and depth[j] + 1 >= limit[j] and xs < fs
                if forced or fs <= xs:
                    b += fs
                    f += 1
                    forced_n += forced
                    depth[j] = 0
                else:
                    b += xs
                    depth[j] += 1
            bytes_per_cp[i] = b
            full_per_cp[i] = f
            forced_per_cp[i] = forced_n
        links_per_cp[i] = int((depth[nonzero] + 1).sum())
        max_depth = max(max_depth, int(depth.max()) if n else 0)
    return bytes_per_cp, forced_per_cp, links_per_cp, max_depth


def pct(a, p):
    return float(np.percentile(a, p)) if len(a) else 0.0


def main():
    sessions = datasets.sessions()
    lines = ["# E1 results - chain length limit per piece", "",
             "Generated by `run.py`. Per session and region: stored bytes per frame (mean); **forced** Full stores per "
             "frame (p99 / max, excluding the baseline): pieces stored in full only because of the key frame or the "
             "chain limit, i.e. the spike; decode links for a full restore (p50 / p99 / max over checkpoints); the "
             "deepest chain.", ""]
    summary = {p.name: [] for p in POLICIES}
    for name, path in sessions:
        st = ps.load(name, path)
        for rname, rs in st.regions.items():
            if rs.pieces == 0 or len(rs.change_cp) == 0:
                continue
            lines += [f"## {name} - {rname} ({rs.pieces} pieces, {rs.checkpoints} checkpoints, "
                      f"{len(rs.change_cp) / max(1, rs.checkpoints - 1):.2f} changed pieces per frame)", "",
                      "| Policy | Bytes/frame | Forced Full p99 | Forced Full max | Restore links p50 | p99 | max | Max depth |",
                      "|---|---|---|---|---|---|---|---|"]
            v1_bytes = None
            for pol in POLICIES:
                b, f, l, md = simulate(rs, pol)
                bpf = float(b[1:].mean())
                if pol.kind == "v1":
                    v1_bytes = bpf
                lines.append(f"| {pol.name} | {bpf:,.0f} | {pct(f[1:], 99):.0f} | {int(f[1:].max())} | "
                             f"{pct(l, 50):,.0f} | {pct(l, 99):,.0f} | {int(l.max()):,} | {md} |")
                summary[pol.name].append((name, rname, bpf / v1_bytes if v1_bytes else 1.0,
                                          int(f[1:].max()), pct(l, 99), md))
            lines.append("")

    # cross-session summary
    head = ["## Summary over all sessions and regions", "",
            "Bytes relative to v1 (geometric mean), the worst forced-Full spike, the worst restore p99 and the "
            "deepest chain over all inputs.", "",
            "| Policy | Bytes vs v1 | Worst forced Full/frame | Worst restore links p99 | Deepest chain |", "|---|---|---|---|---|"]
    for pol in POLICIES:
        rows = summary[pol.name]
        ratios = np.array([r[2] for r in rows if r[2] > 0])
        gm = float(np.exp(np.log(ratios).mean())) if len(ratios) else 1.0
        head.append(f"| {pol.name} | {gm:.3f} | {max(r[3] for r in rows)} | {max(r[4] for r in rows):,.0f} | "
                    f"{max(r[5] for r in rows)} |")
    head.append("")
    with open(os.path.join(HERE, "results.md"), "w", newline="\n") as out:
        out.write("\n".join(lines[:4] + head + lines[4:]) + "\n")
    print("\n".join(head))


if __name__ == "__main__":
    main()
