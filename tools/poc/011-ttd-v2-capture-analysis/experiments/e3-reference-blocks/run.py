"""E3 - copy-on-write page reference table: block size and one vs two levels.

For every checkpoint, the table says which stored piece holds each 4 KB piece
of a region. v1 writes the whole table (4 bytes per piece) into every
checkpoint, in memory and in the file. Phase 1 cuts it into blocks shared
between checkpoints until a piece in the block gets a new slot.

Per input session and region this replays the real change history and reports
the table bytes per frame:
- v1 dense: 4 B per piece, every frame;
- one level: every checkpoint holds one 8-byte pointer per block, plus the
  blocks it had to clone;
- two levels: the per-region block table is itself shared; a checkpoint holds
  one pointer per region, plus a cloned block table when any block changed,
  plus the cloned blocks;
- file (sparse records): a 4-byte count, then per changed block a
  (region u16, position u32, block index u32) triple and, the first time a block
  appears, its contents.

Run: python3 run.py   (after ../common/record-datasets.sh). Writes results.md.
"""

from __future__ import annotations

import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "common"))
import datasets  # noqa: E402
import piecestats as ps  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
BLOCK_PAGES = [4, 8, 16, 32, 64]     # 16 KB pages per block = 4 pieces each
PTR = 8                              # bytes per pointer in memory
REF = 4                              # bytes per piece reference (slot id)
TRIPLE = 2 + 4 + 4


def table_cost(rs: ps.RegionStats, block_pages: int):
    per_block = block_pages * 4                      # pieces per block
    nblocks = -(-rs.pieces // per_block)
    changes = rs.changes_at()
    # a block covers per_block pieces, the last one only what is left of the region
    sizes = np.array([min(per_block, rs.pieces - k * per_block) for k in range(nblocks)], np.int64) * REF
    touched = np.zeros(len(changes) - 1, np.int64)
    touched_bytes = np.zeros(len(changes) - 1, np.int64)
    for i, c in enumerate(changes[1:]):
        if len(c):
            blocks = np.unique(c // per_block)
            touched[i] = len(blocks)
            touched_bytes[i] = int(sizes[blocks].sum())
    one_level = nblocks * PTR + touched_bytes
    two_level = PTR + np.where(touched > 0, nblocks * PTR, 0) + touched_bytes
    file_sparse = 4 + touched * TRIPLE + touched_bytes
    return one_level.mean(), two_level.mean(), file_sparse.mean(), touched.mean(), nblocks


def main():
    lines = ["# E3 results - copy-on-write reference table", "",
             "Generated by `run.py`. Table bytes per frame (mean over checkpoints after the baseline).", ""]
    summary = {b: [] for b in BLOCK_PAGES}
    for name, path in datasets.sessions():
        st = ps.load(name, path)
        for rname, rs in st.regions.items():
            dense = rs.pieces * REF
            lines += [f"## {name} - {rname} ({rs.pieces} pieces; v1 dense table {dense:,} B per frame in memory "
                      "and in the file)", "",
                      "| Block (pages) | Blocks | Blocks cloned / frame | One level, memory | Two levels, memory | "
                      "File, sparse |", "|---|---|---|---|---|---|"]
            for b in BLOCK_PAGES:
                one, two, fil, t, nb = table_cost(rs, b)
                lines.append(f"| {b} | {nb} | {t:.2f} | {one:,.0f} | {two:,.0f} | {fil:,.0f} |")
                summary[b].append((dense, one, two, fil))
            lines.append("")
    head = ["## Summary over all sessions and regions", "",
            "Sum of table bytes per frame over all inputs, relative to v1's dense table.", "",
            "| Block (pages) | One level, memory | Two levels, memory | File, sparse |", "|---|---|---|---|"]
    for b in BLOCK_PAGES:
        d = sum(x[0] for x in summary[b])
        head.append(f"| {b} | {sum(x[1] for x in summary[b]) / d:.3f} | {sum(x[2] for x in summary[b]) / d:.3f} | "
                    f"{sum(x[3] for x in summary[b]) / d:.3f} |")
    head.append("")
    with open(os.path.join(HERE, "results.md"), "w", newline="\n") as out:
        out.write("\n".join(lines[:4] + head + lines[4:]) + "\n")
    print("\n".join(head))


if __name__ == "__main__":
    main()
