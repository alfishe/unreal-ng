"""E4 - restore only the pieces that differ.

A v1 seek decodes every non-zero piece of memory into live RAM. Phase 1
proposes decoding only the pieces whose stored version differs from what live
memory holds, plus the pieces written since (by a replay into the frame).

For seek pairs drawn from every input session this counts the pieces each
approach decodes and estimates the time:
- step: seek one frame back (stepping back through history);
- scrub: seek 1-10 frames back (dragging the timeline);
- jump: from a random position to a random position.
Each pair is evaluated both from a checkpoint and from a position inside the
next frame (live memory then also holds what the replay wrote, which is what
the following frame changes).

Time per piece = one Full decode plus one XOR link per chain step, with the
chain depth simulated under the Phase 1 rule (per-piece limit K = 50, v1 encoder
otherwise) and the per-call times measured by E2 (../e2-encode-once/timing.json).

Run: python3 run.py   (after E2). Writes results.md.
"""

from __future__ import annotations

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "common"))
import datasets  # noqa: E402
import piecestats as ps  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
K = 50
PAIRS = 400
# Writing an all-zero piece into live RAM. v1's baseline stores every piece,
# zero ones as Zero slots, so a full restore writes all of installed memory.
# Calibrated against the Phase 0 benchmark (BM-6 memory restore p50) - see README
ZERO_PIECE_US = 0.55
RNG = np.random.default_rng(0x5EE4)


def depths_per_checkpoint(rs: ps.RegionStats):
    """Chain depth of every piece at every checkpoint (K = 50 per piece) and the non-zero mask."""
    n = rs.pieces
    depth = np.zeros(n, np.int64)
    nonzero = rs.key_full[0] > 0
    order = np.argsort(rs.change_cp, kind="stable")
    rows = {}
    for r in order:
        rows.setdefault(int(rs.change_cp[r]), []).append(r)
    dep = np.zeros((rs.checkpoints, n), np.int16)
    nz = np.zeros((rs.checkpoints, n), bool)
    nz[0] = nonzero
    for i in range(1, rs.checkpoints):
        for r in rows.get(i, []):
            j = int(rs.change_piece[r])
            xs, fs = int(rs.change_xor[r]), int(rs.change_full[r])
            nonzero[j] = fs > 0
            if fs == 0 or depth[j] + 1 >= K or fs <= xs:
                depth[j] = 0
            else:
                depth[j] += 1
        dep[i] = depth
        nz[i] = nonzero
    return dep, nz


def main():
    with open(os.path.join(HERE, "..", "e2-encode-once", "timing.json")) as f:
        tm = json.load(f)
    t_full, t_link = tm["decompress_full_us"], tm["decompress_xor_us"]

    lines = ["# E4 results - restore only the pieces that differ", "",
             f"Generated by `run.py`. Time model: {t_full} µs per Full decode + {t_link} µs per XOR link "
             f"(E2 timing.json) + {ZERO_PIECE_US} µs per all-zero piece written, chain depths under a per-piece "
             f"limit K = {K}. {PAIRS} seek pairs per session and scenario. Figures are p50 / p99 over the pairs. "
             "Full-restore piece counts are the non-zero pieces; the zero pieces it also writes are in its time.", ""]
    summary = {}
    for name, path in datasets.sessions():
        st = ps.load(name, path)
        for rname, rs in st.regions.items():
            if rs.checkpoints < 20:
                continue
            dep, nz = depths_per_checkpoint(rs)
            changes = rs.changes_at()
            cps = rs.checkpoints
            lines += [f"## {name} - {rname} ({rs.pieces} pieces)", "",
                      "| Scenario | Full restore: pieces | Full restore: µs | Differing only: pieces | "
                      "Differing only: µs |", "|---|---|---|---|---|"]
            for scen in ("step", "scrub", "jump"):
                for inside in (False, True):
                    full_p, full_t, diff_p, diff_t = [], [], [], []
                    for _ in range(PAIRS):
                        if scen == "step":
                            a = int(RNG.integers(2, cps - 1)); b = a - 1
                        elif scen == "scrub":
                            a = int(RNG.integers(12, cps - 1)); b = a - int(RNG.integers(1, 11))
                        else:
                            a, b = (int(x) for x in RNG.integers(1, cps - 1, 2))
                        lo, hi = min(a, b), max(a, b)
                        differ = set()
                        for i in range(lo + 1, hi + 1):
                            differ.update(changes[i].tolist())
                        if inside and a + 1 < cps:
                            differ.update(changes[a + 1].tolist())   # written by the replay into frame a
                        target_nz = nz[b]
                        cost = t_full + dep[b].astype(np.float64) * t_link
                        full_p.append(int(target_nz.sum()))
                        full_t.append(float(cost[target_nz].sum()) + ZERO_PIECE_US * int((~target_nz).sum()))
                        d = np.fromiter(differ, np.int64) if differ else np.empty(0, np.int64)
                        dz = d[~target_nz[d]] if len(d) else d          # differing, now all-zero
                        d = d[target_nz[d]] if len(d) else d
                        diff_p.append(len(d) + len(dz))
                        diff_t.append((float(cost[d].sum()) if len(d) else 0.0) + ZERO_PIECE_US * len(dz))
                    label = scen + (" (from inside a frame)" if inside else "")
                    f = lambda a: f"{np.percentile(a, 50):,.0f} / {np.percentile(a, 99):,.0f}"
                    lines.append(f"| {label} | {f(full_p)} | {f(full_t)} | {f(diff_p)} | {f(diff_t)} |")
                    summary.setdefault(label, []).append((name, rname, np.percentile(full_t, 99),
                                                          np.percentile(diff_t, 99)))
            lines.append("")
    head = ["## Summary", "",
            "Worst p99 over all sessions and regions (µs of memory decode for one seek).", "",
            "| Scenario | Full restore | Differing only | Where the worst case is |", "|---|---|---|---|"]
    for label, rows in summary.items():
        worst_full = max(rows, key=lambda r: r[2])
        worst_diff = max(rows, key=lambda r: r[3])
        head.append(f"| {label} | {worst_full[2]:,.0f} | {worst_diff[3]:,.0f} | {worst_diff[0]} {worst_diff[1]} |")
    head.append("")
    with open(os.path.join(HERE, "results.md"), "w", newline="\n") as out:
        out.write("\n".join(lines[:4] + head + lines[4:]) + "\n")
    print("\n".join(head))


if __name__ == "__main__":
    main()
