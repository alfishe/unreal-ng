"""E6 - run the v1 / v2 data model on the real-use sessions and write results.md.

Run: python3 run.py   (after ../common/record-real-sessions.sh)

For every session of scratch/ttd-experiments/real/{1min,5min}/:
1. the v1 model against the benchmark's measured heap split (does the model
   explain v1's memory?) and against the real file size;
2. per stream, MB per minute of recording (3,000 frames) in memory and in the
   file, v1 and v2, with the reason;
3. the seek work: mean XOR links decoded per non-zero piece.
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import model  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", ".."))
REAL = os.path.join(ROOT, "scratch", "ttd-experiments", "real")
FRAMES_PER_MINUTE = 3000
MB = 1e6

CASES = [
    ("PENTAGON_idle", "Pentagon 128, BASIC prompt"),
    ("PENTAGON_game", "Pentagon 128, game with input"),
    ("PENTAGON_demo", "Pentagon 128, 7th Reality"),
    ("PENTAGON_demo2", "Pentagon 128, Across the Edge"),
    ("PENTAGON_demo-eyeache", "Pentagon 128, Eye Ache"),
    ("ATM3_idle", "ZX-Evo, BASIC prompt"),
]

MEASURED = {   # model stream -> benchmark heap parts (bm4_heap_<part>_bpf)
    "memory pieces": ("ram_payload", "ram_payload_slack", "page_store_table"),
    "reference table": ("page_refs",),
    "device state": ("device_blobs",),
    "CPU + chipset": ("checkpoints",),
    "write journal": ("write_journal",),
    "coverage": ("coverage",),
    "port journals": ("port_reads", "port_writes"),
}


def bench_cases(length: str):
    with open(os.path.join(REAL, length, "bench.json")) as f:
        data = json.load(f)
    out = {}
    for b in data["benchmarks"]:
        parts = b["name"].split("/")
        out[f"{parts[2]}_{parts[3]}"] = b
    return out


def measured(b, stream: str) -> float:
    return sum(b.get(f"bm4_heap_{p}_bpf", 0.0) for p in MEASURED.get(stream, ())) * b["frames"]


def run_length(length: str, lines: list):
    bench = bench_cases(length)
    models = []
    for case, label in CASES:
        b = bench[case]
        path = os.path.join(REAL, length, f"ttd-bench-v1-{case}.ttd")
        dump_cov = model.tf.parse_file(path).coverage
        bound = sum(model.zstd_bound(bl.raw_size) for k in dump_cov.kinds for bl in k.blocks) if dump_cov else 0
        m = model.model_session(f"real-{length}-{case}", path,
                                journal_records_per_frame=b["bm3_journal_writes_opf"],
                                coverage_working_set=max(0.0, measured(b, "coverage") - bound))
        models.append((case, label, b, m))
        print(f"{length} {case}: done", flush=True)

    scale = FRAMES_PER_MINUTE / models[0][3].frames
    lines += [f"## {length} sessions ({models[0][3].frames:,} frames)", "",
              "### Does the v1 model explain v1? (MB for the whole session)", "",
              "| Session | Memory: model | Memory: measured | File: model | File: real |", "|---|---|---|---|---|"]
    for case, label, b, m in models:
        lines.append(f"| {label} | {m.total('v1_mem') / MB:.1f} | {b['bm4_resident_bytes'] / MB:.1f} | "
                     f"{m.total('v1_file') / MB:.1f} | {m.file_bytes / MB:.1f} |")
    lines += ["", "### Per stream, MB per minute of recording", ""]
    for case, label, b, m in models:
        lines += [f"**{label}**", "",
                  "| Stream | v1 memory | v2 memory | v1 file | v2 file | Why |", "|---|---|---|---|---|---|"]
        for s in m.streams.values():
            lines.append(f"| {s.name} | {s.v1_mem * scale / MB:.1f} | {s.v2_mem * scale / MB:.1f} | "
                         f"{s.v1_file * scale / MB:.2f} | {s.v2_file * scale / MB:.2f} | {s.why} |")
        lines.append(f"| **total** | **{m.total('v1_mem') * scale / MB:.1f}** | **{m.total('v2_mem') * scale / MB:.1f}** | "
                     f"**{m.total('v1_file') * scale / MB:.2f}** | **{m.total('v2_file') * scale / MB:.2f}** | |")
        lines += ["", f"Seek work, mean XOR links per non-zero piece: v1 {m.seek.v1_links:.1f}, "
                      f"v2 {m.seek.v2_links:.1f}.", ""]
    lines += ["### Summary, MB per minute", "",
              "| Session | v1 memory | v2 memory | v1 file | v2 file |", "|---|---|---|---|---|"]
    for case, label, b, m in models:
        lines.append(f"| {label} | {m.total('v1_mem') * scale / MB:.1f} | {m.total('v2_mem') * scale / MB:.1f} | "
                     f"{m.total('v1_file') * scale / MB:.2f} | {m.total('v2_file') * scale / MB:.2f} |")
    lines.append("")


def main():
    lines = ["# E6 results - TTD v1 and v2 data model on real-use sessions", "",
             "Generated by run.py. Per-minute figures are per 3,000 frames (one minute at 50 frames per second).", ""]
    for length in ("1min", "5min"):
        if os.path.exists(os.path.join(REAL, length, "bench.json")):
            run_length(length, lines)
    with open(os.path.join(HERE, "results.md"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
