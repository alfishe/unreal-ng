#!/usr/bin/env python3
"""Write data/controllers/profiles/games/index.yaml (mapping-and-profiles.md §7.5).

Reads every game file and bundle under games/ (one YAML document per profile, `---` between them) and lists each
profile with its id, label, machines, file, byte offset and length, and the keys it is found by (`sha256:<hex>`,
`sig:<signature>`, `zxdb:<id>`) with its TR-DOS file set (`file_set`, for the catalog rule). The emulator reads only the
index at start and parses a profile when a key of the loaded program names it; it rebuilds the index in memory when
this file is missing or older than a profile, so the tool is for the committed copy.

    tools/controllers/profile-index.py            # write the index
    tools/controllers/profile-index.py --check    # exit 1 when the committed index is not what the files say
"""

import argparse
import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
GAMES = ROOT / "data" / "controllers" / "profiles" / "games"
HEADER = "# games/index.yaml - generated by tools/controllers/profile-index.py: do not edit\n"
MARKER = re.compile(rb"^---(?:[ \t\r].*)?$")
PLAIN = re.compile(r"^[A-Za-z0-9_\x80-\U0010ffff][A-Za-z0-9_ ./+()\-\x80-\U0010ffff]*$")
NUMBER = re.compile(r"^[-+]?(\d+(\.\d*)?|\.\d+)([eE][-+]?\d+)?$|^0x[0-9a-fA-F]+$|^0o[0-7]+$")
RESERVED = {"y", "n", "yes", "no", "on", "off", "true", "false", "null"}


def documents(data):
    """[offset, length) of each non-empty YAML document of a file, as the emulator's SplitYamlDocuments splits it."""
    starts = [0]
    pos = 0
    for line in data.split(b"\n"):
        if pos != 0 and MARKER.match(line):
            starts.append(pos)
        pos += len(line) + 1
    out = []
    for i, start in enumerate(starts):
        end = starts[i + 1] if i + 1 < len(starts) else len(data)
        body = [l.strip() for l in data[start:end].split(b"\n")]
        if any(l and not l.startswith(b"#") and not MARKER.match(l) for l in body):
            out.append((start, end - start))
    return out


def keys_of(match):
    keys = ["sha256:" + str(sha).lower() for sha in match.get("file_sha256", [])]
    keys += ["sig:" + str(sig).lower() for sig in match.get("signatures", [])]
    zxdb = match.get("zxdb_id")
    for zid in (zxdb if isinstance(zxdb, list) else [zxdb] if zxdb is not None else []):
        keys.append("zxdb:" + (str(int(zid)) if isinstance(zid, (int, float)) else str(zid).lower()))
    return keys


def build(errors):
    entries, ids, owners = [], {}, {}
    files = sorted(p for p in GAMES.rglob("*.yaml") if p.relative_to(GAMES).as_posix() != "index.yaml")
    for path in files:
        relative = path.relative_to(GAMES).as_posix()
        data = path.read_bytes()
        for offset, length in documents(data):
            where = relative + (f" at byte {offset}" if offset else "")
            try:
                profile = yaml.safe_load(data[offset:offset + length].decode("utf-8"))
            except (yaml.YAMLError, UnicodeDecodeError) as e:
                errors.append(f"{where}: {e}")
                continue
            match = profile.get("match", {}) if isinstance(profile, dict) else {}
            if (not isinstance(profile, dict) or profile.get("kind") != "play" or
                    not (match.get("file_sha256") or match.get("signatures") or match.get("file_set"))):
                errors.append(f"{where}: not a game profile (a play profile with match.file_sha256, signatures or "
                              "file_set)")
                continue
            pid = str(profile.get("id", ""))
            if pid in ids:
                errors.append(f"{where}: '{pid}' is also {ids[pid]}")
                continue
            ids[pid] = where
            keys = keys_of(match)
            clash = [k for k in keys if owners.get(k, pid) != pid]
            for k in clash:
                errors.append(f"{where}: {k} also names '{owners[k]}'")
            if clash:
                continue
            owners.update({k: pid for k in keys})
            entries.append({"id": pid, "label": profile.get("label"), "machines": match.get("machines", []),
                            "file": relative, "offset": offset, "length": length, "keys": keys,
                            "file_set": [str(t).lower() for t in match.get("file_set", [])]})
    return entries


def scalar(value):
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return str(value)
    text = str(value)
    if PLAIN.match(text) and text.strip() == text and text.lower() not in RESERVED and not NUMBER.match(text):
        return text
    return json.dumps(text, ensure_ascii=False)


def dump(entries):
    lines = [HEADER.rstrip("\n"), "version: 1", "profiles:"]
    for e in entries:
        fields = [f"id: {scalar(e['id'])}"]
        if e["label"]:
            fields.append(f"label: {scalar(e['label'])}")
        if e["machines"]:
            fields.append("machines: [" + ", ".join(scalar(m) for m in e["machines"]) + "]")
        fields += [f"file: {scalar(e['file'])}", f"offset: {e['offset']}", f"length: {e['length']}",
                   "keys: [" + ", ".join(scalar(k) for k in e["keys"]) + "]"]
        if e["file_set"]:
            fields.append("file_set: [" + ", ".join(scalar(t) for t in e["file_set"]) + "]")
        lines.append("  - { " + ", ".join(fields) + " }")
    if not entries:
        lines[-1] = "profiles: []"
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="compare with the committed index, write nothing")
    args = parser.parse_args()
    errors = []
    text = dump(build(errors))
    for error in errors:
        print(f"profile-index: {error}", file=sys.stderr)
    index = GAMES / "index.yaml"
    if args.check:
        if not index.exists() or index.read_text(encoding="utf-8") != text:
            print(f"profile-index: {index.relative_to(ROOT)} is stale: run tools/controllers/profile-index.py",
                  file=sys.stderr)
            return 1
        return 1 if errors else 0
    index.write_text(text, encoding="utf-8")
    print(f"profile-index: {index.relative_to(ROOT)}, {text.count(chr(10)) - 3} profiles")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
