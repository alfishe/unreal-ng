#!/usr/bin/env python3
"""A software profile's `memory:` section from a reverse's annotation file (the unrealng-reverse-cases kit's
`game.ann`, docs/ann-format.md there): one region per entry (code, bytes, words, text, space) up to the next entry,
its kind from the entry type and the module it is in, the entry's name and title; a label for every entry, inner
label, @var and @equ; the code entries and the labels inside them as entries (instruction starts for the
disassembler); the inner comments as comments.

    tools/controllers/ann-memory-profile.py <game.ann> --id builtin/game/zynaps --label Zynaps \\
        --machines 48K,128K,PENTAGON --sha256 <tape sha256> [--header <text file>] [--kind module=kind ...] \\
        [--end 0xFFFF] -o data/software/pentagon/zynaps.yaml

The kinds are the analysis RegionKind names (code, data, text, font, sprite, tile, screen, buffer, init_table,
records, variable, pointer_table, handler_table, rng, music, packed, level_map, unused). A data entry takes the kind
--kind gives its module, else words are a pointer_table, text is text, space is a buffer, bytes are data. Run
tools/controllers/profile-index.py afterwards."""

import argparse
import re
import sys

ENTRY = re.compile(r'^\$([0-9A-Fa-f]{4})\s+([cbwts])\s+([A-Za-z_][\w]*)(?:\s+\d+)?\s*(?:;\s*(.*))?$')
LABEL = re.compile(r'^\$([0-9A-Fa-f]{4})\s+([A-Za-z_][\w]*)?\s*(?:;\s*(.*))?$')
EQU = re.compile(r'^@(?:equ|var)\s+\$([0-9A-Fa-f]{4})\s+([A-Za-z_][\w]*)(?:\s+\d+)?\s*(?:;\s*(.*))?$')
MODULE = re.compile(r'^@module\s+(\S+)')
OLD_FORM = re.compile(r'^#\s*(@(?:bank|var|alias|over|piece)\b.*)$')
KINDS = {'code', 'data', 'text', 'font', 'sprite', 'tile', 'screen', 'buffer', 'init_table', 'records', 'variable',
         'pointer_table', 'handler_table', 'rng', 'music', 'packed', 'level_map', 'unused'}


def quote(text):
    """A YAML double-quoted scalar"""
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def short(text, limit=96):
    text = ' '.join(text.split())
    return text if len(text) <= limit else text[:limit - 3].rstrip() + '...'


def parse(path):
    entries, labels, comments = [], [], []
    module = ''
    for line in open(path, encoding='utf-8'):
        text = line.strip()
        old = OLD_FORM.match(text)
        if old:
            text = old.group(1)
        if not text or (text.startswith('#') and not old):
            continue
        m = MODULE.match(text)
        if m:
            module = m.group(1)
            continue
        m = ENTRY.match(text)
        if m:
            entries.append({'at': int(m.group(1), 16), 'type': m.group(2), 'name': m.group(3),
                            'title': (m.group(4) or '').strip(), 'module': module})
            continue
        m = EQU.match(text)
        if m:
            labels.append((int(m.group(1), 16), m.group(2), (m.group(3) or '').strip(), False))
            continue
        m = LABEL.match(text)
        if m and (m.group(2) or m.group(3)):
            address = int(m.group(1), 16)
            if m.group(2):
                labels.append((address, m.group(2), (m.group(3) or '').strip(), True))
            elif m.group(3):
                comments.append((address, m.group(3).strip()))
    return entries, labels, comments


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('ann')
    parser.add_argument('--id', required=True)
    parser.add_argument('--label', required=True)
    parser.add_argument('--machines', required=True, help='comma list: 48K,128K,PENTAGON')
    parser.add_argument('--sha256', action='append', default=[], help='a tape / disk image SHA-256 (repeat)')
    parser.add_argument('--header', help='a text file: the comment lines on top of the profile')
    parser.add_argument('--kind', action='append', default=[], help='module=kind for the data entries of a module')
    parser.add_argument('--end', default='0xFFFF', help='the last address of the last entry')
    parser.add_argument('-o', '--output', required=True)
    args = parser.parse_args()

    module_kinds = {}
    for item in args.kind:
        module, _, kind = item.partition('=')
        if kind not in KINDS:
            sys.exit(f'--kind {item}: not a region kind ({", ".join(sorted(KINDS))})')
        module_kinds[module] = kind

    entries, labels, comments = parse(args.ann)
    if not entries:
        sys.exit(f'{args.ann}: no entries')
    entries.sort(key=lambda e: e['at'])
    end = int(args.end, 0)
    code_ranges = []
    out = []
    if args.header:
        out += ['# ' + line.rstrip() if line.strip() else '#' for line in open(args.header, encoding='utf-8')]
    out += ['# The memory section is generated by tools/controllers/ann-memory-profile.py from the reverse\'s',
            f'# annotations ({len(entries)} entries, {len(labels)} labels): do not edit it by hand.',
            'schema: 1', 'kind: play', f'id: {args.id}', f'label: {quote(args.label)}', 'match:',
            f'  machines: [{", ".join(m.strip() for m in args.machines.split(","))}]', '  file_sha256:']
    out += [f'    - "{sha.lower()}"' for sha in args.sha256]
    out += ['memory:', '  regions:']
    for index, entry in enumerate(entries):
        hi = entries[index + 1]['at'] - 1 if index + 1 < len(entries) else end
        if hi < entry['at']:
            continue
        kind = {'c': 'code', 't': 'text'}.get(entry['type'])
        if kind is None:
            kind = module_kinds.get(entry['module']) or {'w': 'pointer_table', 's': 'buffer'}.get(entry['type'], 'data')
        if kind == 'code':
            code_ranges.append((entry['at'], hi))
        title = entry['name'] + (': ' + short(entry['title']) if entry['title'] else '')
        out.append(f'    - {{at: "0x{entry["at"]:04X}-0x{hi:04X}", kind: {kind}, title: {quote(title)}}}')

    in_code = lambda address: any(lo <= address <= hi for lo, hi in code_ranges)
    named = {}
    for entry in entries:
        named.setdefault(entry['at'], (entry['name'], short(entry['title'])))
    for address, name, comment, inner in labels:
        named.setdefault(address, (name, short(comment)))
    out.append('  labels:')
    for address in sorted(named):
        name, comment = named[address]
        line = f'    - {{name: {name}, at: "0x{address:04X}"'
        out.append(line + (f', comment: {quote(comment)}}}' if comment else '}'))
    starts = sorted({e['at'] for e in entries if e['type'] == 'c'} |
                    {address for address, _, _, inner in labels if inner and in_code(address)})
    out.append('  entries:')
    out += [f'    - {{name: {named[a][0] if a in named else "entry"}, at: "0x{a:04X}"}}' for a in starts]
    out.append('  comments:')
    seen = set()
    for address, name, comment, inner in labels:
        if inner and comment and address not in seen and not any(e['at'] == address for e in entries):
            seen.add(address)
            out.append(f'    - {{at: "0x{address:04X}", text: {quote(short(comment, 160))}}}')
    for address, text in comments:
        if address not in seen:
            seen.add(address)
            out.append(f'    - {{at: "0x{address:04X}", text: {quote(short(text, 160))}}}')
    with open(args.output, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print(f'{args.output}: {len(entries)} regions, {len(named)} labels, {len(starts)} entries, {len(seen)} comments')


if __name__ == '__main__':
    main()
