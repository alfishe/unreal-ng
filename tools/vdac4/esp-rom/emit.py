#!/usr/bin/env python3
"""Write esprom.cpp from the linked ROM (see build.sh)."""
import re
import sys

here, out, target, rom_base, trap_base, compiler = sys.argv[1:7]
rom_base = int(rom_base, 16)
trap_base = int(trap_base, 16)
image = open(f"{out}/rom.bin", "rb").read()

sections = {}
for line in open(f"{out}/rom.size"):
    m = re.match(r"(\.\w+)\s+(\d+)\s+(\d+)", line)
    if m:
        sections[m.group(1)] = (int(m.group(2)), int(m.group(3)))
bss_size, bss_addr = sections.get(".bss", (0, 0))
end = max(rom_base + len(image), bss_addr + bss_size)

symbols = {}
for line in open(f"{out}/rom.nm"):
    parts = line.split()
    if len(parts) == 3:
        symbols[parts[2]] = int(parts[0], 16)

traps = open(f"{here}/traps.txt").read().split()
exports = open(f"{here}/exports.txt").read().split()
for name in exports:
    if name not in traps and name not in symbols:
        sys.exit(f"export {name} not in the ROM")

lines = []
lines.append("// Generated by tools/vdac4/esp-rom/build.sh from the Espressif toolchain's esp32s3 newlib, libm and")
lines.append(f"// libgcc ({compiler}). Do not edit.")
lines.append("")
lines.append('#include "esprom.h"')
lines.append("")
lines.append("namespace vdac4")
lines.append("{")
lines.append("")
lines.append(f"const uint32_t kEspRomBase = 0x{rom_base:08X};")
lines.append(f"const uint32_t kEspRomSize = 0x{(end - rom_base + 0xFFF) & ~0xFFF:X};  // image + .bss, zero-filled, whole 4 KB pages")
lines.append(f"const uint32_t kEspRomImageSize = {len(image)};")
lines.append(f"const uint32_t kEspTrapBase = 0x{trap_base:08X};")
lines.append(f"const uint32_t kEspRomImpureData = 0x{symbols['_impure_data']:08X};")
lines.append("")
lines.append("const uint8_t kEspRomImage[] = {")
for i in range(0, len(image), 24):
    lines.append("    " + ", ".join(f"0x{b:02X}" for b in image[i:i + 24]) + ",")
lines.append("};")
lines.append("")
lines.append("const EspRomSymbol kEspRomTraps[] = {")
for i, name in enumerate(traps):
    lines.append(f'    {{"{name}", 0x{trap_base + 4 * i:08X}}},')
lines.append("};")
lines.append(f"const size_t kEspRomTrapCount = {len(traps)};")
lines.append("")
lines.append("// Firmware exports (libc, esp-idf, zm_symbols tables) that the ROM code provides")
lines.append("const EspRomSymbol kEspRomExports[] = {")
count = 0
for name in exports:
    if name in traps:
        continue
    lines.append(f'    {{"{name}", 0x{symbols[name]:08X}}},')
    count += 1
lines.append("};")
lines.append(f"const size_t kEspRomExportCount = {count};")
lines.append("")
lines.append("}  // namespace vdac4")
open(target, "w").write("\n".join(lines) + "\n")
print(f"{target}: image {len(image)} bytes, {count} exports, {len(traps)} traps")
