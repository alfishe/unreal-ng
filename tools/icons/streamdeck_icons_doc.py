#!/usr/bin/env python3
"""Writes docs/companions/streamdeck/icons/glyphs.md: every Stream Deck glyph and what it is bound to.

    python3 tools/icons/streamdeck_icons_doc.py

Generated from data/streamdeck/icons/glyphs.json (do not edit glyphs.md by hand: edit
tools/icons/streamdeck_glyphs.py, run it, then this). For each glyph: its id, title, what the picture shows (the
brief every pack draws), the catalogue actions that show it (as their face, as their "on" face with the readout that
switches it, or for one parameter value) and the menus / navigation keys that use it.
"""

import json
import os

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT_DIR, 'data', 'streamdeck', 'icons', 'glyphs.json')
OUT = os.path.join(ROOT_DIR, 'docs', 'companions', 'streamdeck', 'icons', 'glyphs.md')
PACKS = os.path.join(ROOT_DIR, 'data', 'streamdeck', 'icons', 'packs')


def cell(s):
    return str(s).replace('|', '\\|')


def main():
    with open(SRC) as f:
        d = json.load(f)
    glyphs = d['glyphs']
    uses = {g['id']: [] for g in glyphs}
    for action, m in d['actions'].items():
        if m.get('face') in uses:
            uses[m['face']].append('`%s`' % action)
        if m.get('face_on') in uses:
            uses[m['face_on']].append('`%s` on (`%s`)' % (action, m.get('state', '')))
        for value, gid in (m.get('params') or {}).items():
            if gid in uses:
                uses[gid].append('`%s` %s' % (action, value))
    for what, gids in d['navigation'].items():
        for gid in gids if isinstance(gids, list) else [gids]:
            if gid in uses:
                uses[gid].append(what)
    packs = sorted(p for p in os.listdir(PACKS) if os.path.isfile(os.path.join(PACKS, p, 'pack.json')))

    lines = ['# Stream Deck glyphs', '',
             '> Generated by `tools/icons/streamdeck_icons_doc.py` from `data/streamdeck/icons/glyphs.json`: do not '
             'edit by hand.', '',
             '%d glyphs in %d groups; %d catalogue actions have a face, %d are pruned (no key face). Every pack in '
             '`data/streamdeck/icons/packs/` draws all of them: %s. How the packs are made and changed: '
             '[README.md](README.md).' % (len(glyphs), len(d['groups']), len(d['actions']), len(d['pruned']),
                                          ', '.join('`%s`' % p for p in packs)), '',
             'A glyph id ending in `.on` is the state variant of the glyph without it: the face while the action\'s '
             'readout is true. "Used by" lists the catalogue actions showing the glyph (`id` = its face, `id` on = '
             'its on face with the readout, `id` value = for that parameter value) and the menus / navigation keys.',
             '']
    for group in d['groups']:
        gl = [g for g in glyphs if g['group'] == group['id']]
        if not gl:
            continue
        lines += ['## %s (`%s`, %d)' % (group['title'], group['id'], len(gl)), '',
                  '| Glyph | Title | Draws | Used by |', '|:--|:--|:--|:--|']
        for g in gl:
            used = ', '.join(uses[g['id']]) or '-'
            if g.get('variant_of'):
                used = 'state of `%s`; %s' % (g['variant_of'], used)
            lines.append('| `%s` | %s | %s | %s |' % (g['id'], cell(g['title']), cell(g['draw']), cell(used)))
        lines.append('')
    lines += ['## Catalogue actions and their faces', '',
              '| Action | Face | On face | Readout | Per parameter | Key label |', '|:--|:--|:--|:--|:--|:--|']
    for action, m in sorted(d['actions'].items()):
        params = '; '.join('%s: `%s`' % (k, v) for k, v in (m.get('params') or {}).items())
        lines.append('| `%s` | `%s` | %s | %s | %s | %s |' % (
            action, m.get('face', ''), ('`%s`' % m['face_on']) if m.get('face_on') else '',
            ('`%s`' % m['state']) if m.get('state') else '', cell(params), cell(m.get('label', m.get('note', '')))))
    lines += ['', '## Pruned actions (no key face)', '', '| Action | Why |', '|:--|:--|']
    for action, why in sorted(d['pruned'].items()):
        lines.append('| `%s` | %s |' % (action, cell(why)))
    lines.append('')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(lines))
    print('glyphs.md: %d glyphs, %d actions -> %s' % (len(glyphs), len(d['actions']), os.path.relpath(OUT, ROOT_DIR)))


if __name__ == '__main__':
    main()
