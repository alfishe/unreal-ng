#!/usr/bin/env python3
"""Generate a General Sound firmware profile (JSON, gs-debugger design §8A.9 M8) from the firmware's sources.

The sources give what a binary cannot: the command table with its handlers' names, the comment that names each
command, the structures. The mark-up tool (markup_symbols.py) gives the addresses in data/symbols/gs/<id>.map.

Read from the sources (any *.a80 under --source):
  - COMTAB  DEFW handler,...   words for commands #00-#1F, then #F0-#FF (the stock split dispatcher, COMINT)
  - COMTABH DB low handler,... low bytes for commands #20-#EF (the high bytes follow 256 later)
  - "; #NN - TEXT" comments before a handler: the command's name
  - --patch: "ORG COMTABH+#NN-#20" / "DB low X" pairs override entries, named by "(new cmd #NN - TEXT)"
  - STRUCT name ... ENDS blocks (sjasmplus: fields "name BYTE|WORD|D24|DWORD|BLOCK n"), and "name EQU base+offset"
    runs after a "; struct <name>" comment: the structures
Handlers that are the "unknown command" stubs (COMZ, COMHZ, or an EQU alias of one) give no command. A handler with no
"; #NN" comment is named by its label (the v1.05a sources comment only the low commands; the built-in profile has
the guide's names).

Usage:
  profile_from_source.py              regenerate the committed profile(s) and compare (exit 1 on a difference)
  profile_from_source.py --write      regenerate and overwrite them
  profile_from_source.py --source DIR --map FILE --id ID --title T [--out FILE]   one profile, to stdout or a file
"""

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FIRMWARE = os.path.join(ROOT, "docs/inprogress/2026-09-19-general-sound/materials/gs/gs-firmware/firmware")

# The committed profiles: regenerated by the check (a test in tools/gsfirmware/test_profile_from_source.py)
COMMITTED = [
    {
        "id": "gs105a-source",
        "title": "General Sound firmware v1.05a (generated from the sources)",
        "source": os.path.join(FIRMWARE, "src"),
        "patch": os.path.join(FIRMWARE, "patch"),  # make_rom.a80 includes patch/patch.a80 (v1.05a / v1.05b)
        "map": os.path.join(ROOT, "data/symbols/gs/gs105a.map"),
        "symbol_file": "gs105a.map",
        "out": os.path.join(ROOT, "tools/gsfirmware/gs105a.profile.json"),
    },
]

STUBS = {"COMZ", "COMHZ"}
FIELD_TYPES = {"BYTE": ("u8", 1), "DB": ("u8", 1), "WORD": ("u16", 2), "DW": ("u16", 2), "D24": ("u24", 3),
               "DWORD": ("u32", 4), "DD": ("u32", 4)}


def read_sources(folder):
    """The lines of every *.a80 under `folder`, in name order: [(file, line)]"""
    lines = []
    for base, _, files in sorted(os.walk(folder)):
        for name in sorted(files):
            if name.lower().endswith(".a80"):
                path = os.path.join(base, name)
                with open(path, "rb") as f:
                    text = f.read().decode("cp866", errors="replace")
                rel = os.path.relpath(path, folder)
                lines += [(rel, line.rstrip("\r\n")) for line in text.split("\n")]
    return lines


def read_map(path):
    """NAME -> (page, address) from a LabelManager map ([ROMn:|RAMn:]ADDR NAME ...)"""
    names = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split(";", 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            where, name = parts[0], parts[1]
            page = None
            if ":" in where:
                page, where = where.split(":", 1)
            try:
                names[name] = (page, int(where, 16))
            except ValueError:
                pass
    return names


def table_words(lines, label, directive):
    """The operands of `label`'s DEFW / DB rows (the label on its own line or on the first row)"""
    out = []
    inside = False
    for _, line in lines:
        code = line.split(";", 1)[0]
        head = code.split()
        if not inside:
            if head and head[0] == label:
                inside = True
                code = code[len(label):] if code.startswith(label) else code
                head = code.split()
                if not head:
                    continue
            else:
                continue
        if not head:
            if out:
                break
            continue
        if head[0].upper() not in directive:
            if out:
                break
            continue
        operands = code.split(None, 1)[1] if len(code.split(None, 1)) > 1 else ""
        for item in operands.split(","):
            item = item.strip()
            item = re.sub(r"^low\s*", "", item, flags=re.I) if re.match(r"^low\b", item, flags=re.I) else item
            item = re.sub(r"^\((.*)\)$", r"\1", item).strip()  # AS: LOW (COM20)
            if item:
                out.append(item)
    return out


def command_names(lines):
    """handler label -> (number, name) from "; #NN - TEXT" comments right before the label"""
    names = {}
    pending = None
    for _, line in lines:
        m = re.match(r"^;\s*#([0-9A-Fa-f]{2})\s*-\s*(.+?)\s*$", line)
        if m:
            pending = (int(m.group(1), 16), m.group(2))
            continue
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)\b", line)
        if m and pending:
            names.setdefault(m.group(1), pending)
            pending = None
        elif line.strip() and not line.lstrip().startswith(";"):
            pending = None if not m else pending
    return names


def sentence(text):
    """'SET VOLUME OF CURRENT CHANNEL' -> 'Set volume of current channel' (words with digits or ' kept)"""
    words = text.split()
    out = []
    for i, w in enumerate(words):
        if w.isupper() and not any(c.isdigit() for c in w) and len(w) > 1:
            w = w.lower()
        out.append(w)
    s = " ".join(out)
    return s[:1].upper() + s[1:]


def structs(lines):
    """STRUCT ... ENDS blocks and '; struct <name>' EQU runs"""
    result = []
    current = None
    offset = 0
    for _, line in lines:
        code = line.split(";", 1)[0].strip()
        m = re.match(r"^STRUCT\s+([A-Za-z_]\w*)", code, re.I)
        if m:
            current = {"name": m.group(1), "fields": []}
            offset = 0
            continue
        if current is not None:
            if re.match(r"^ENDS\b", code, re.I):
                current["size"] = offset
                result.append(current)
                current = None
                continue
            m = re.match(r"^([A-Za-z_]\w*)\s+(BYTE|DB|WORD|DW|D24|DWORD|DD|BLOCK|DS)\b\s*(\d+)?", code, re.I)
            if m:
                kind = m.group(2).upper()
                if kind in ("BLOCK", "DS"):
                    size = int(m.group(3) or "1")
                    current["fields"].append({"name": m.group(1), "offset": offset, "type": "bytes", "size": size})
                else:
                    ftype, size = FIELD_TYPES[kind]
                    current["fields"].append({"name": m.group(1), "offset": offset, "type": ftype})
                offset += size
    # '; struct name' followed by 'FIELD EQU n' lines (offsets), up to a blank line
    current = None
    for _, line in lines:
        m = re.match(r"^;\s*struct\s+([A-Za-z_]\w*)", line, re.I)
        if m:
            current = {"name": m.group(1), "fields": []}
            continue
        if current is not None:
            m = re.match(r"^([A-Za-z_]\w*)\s+EQU\s+(#[0-9A-Fa-f]+|\$[0-9A-Fa-f]+|\d+)\s*$", line.split(";", 1)[0].strip(),
                         re.I)
            if m:
                value = m.group(2)
                offset = int(value[1:], 16) if value[0] in "#$" else int(value)
                current["fields"].append({"name": m.group(1), "offset": offset, "type": "u8"})
                continue
            if current["fields"]:
                result.append(current)
            current = None
    return result


def patched_entries(lines):
    """command -> (handler, name) from a patch's "ORG COMTABH+#NN-#20" / "DB low X" pair, named by the
    "(new cmd #NN - TEXT)" comment above it"""
    out = {}
    names = {}
    org = None
    for _, line in lines:
        m = re.search(r"\(new cmd #([0-9A-Fa-f]{2})\s*-\s*(.+?)\)", line)
        if m:
            names[int(m.group(1), 16)] = m.group(2)
        code = line.split(";", 1)[0].strip()
        m = re.match(r"^ORG\s+COMTABH\s*\+\s*#([0-9A-Fa-f]{2})\s*-\s*#20\s*$", code, re.I)
        if m:
            org = int(m.group(1), 16)
            continue
        m = re.match(r"^(?:DB|DEFB)\s+low\s+([A-Za-z_]\w*)\s*$", code, re.I)
        if m and org is not None:
            out[org] = m.group(1)
        if code:
            org = None
    return {c: (h, names.get(c)) for c, h in out.items()}


def generate(source, map_path, profile_id, title, symbol_file=None, patch=None):
    lines = read_sources(source)
    patches = patched_entries(read_sources(patch)) if patch else {}
    symbols = read_map(map_path)
    names = command_names(lines)
    low = table_words(lines, "COMTAB", ("DEFW", "DW"))
    high = table_words(lines, "COMTABH", ("DB", "DEFB"))
    if len(low) != 0x30 or len(high) != 0xD0:
        raise SystemExit(f"COMTAB has {len(low)} words (48 expected), COMTABH {len(high)} bytes (208 expected)")
    handlers = {}
    for i, h in enumerate(low):
        handlers[i if i < 0x20 else i + 0xD0] = h
    for i, h in enumerate(high):
        handlers[0x20 + i] = h
    for code, (h, name) in patches.items():
        handlers[code] = h
        if name:
            names.setdefault(h, (code, name))
    # "COMF2 EQU COMZ": an alias of a stub is a stub
    aliases = {}
    for _, line in lines:
        m = re.match(r"^([A-Za-z_]\w*)\s+EQU\s+([A-Za-z_]\w*)\s*(;.*)?$", line.strip(), re.I)
        if m:
            aliases[m.group(1)] = m.group(2)

    def resolve(name):
        seen = set()
        while name in aliases and name not in seen:
            seen.add(name)
            name = aliases[name]
        return name

    commands = []
    for code in range(256):
        handler = handlers[code]
        if resolve(handler) in STUBS:
            continue
        number, name = names.get(handler, (code, None))
        entry = {"number": f"{code:02X}", "name": sentence(name) if name else handler, "handler": handler}
        if handler in symbols:
            entry["handler_address"] = f"#{symbols[handler][1]:04X}"
        if number != code:
            entry["range_of"] = f"{number:02X}"  # one handler for a run (#80-#9F, #A0-#AF)
        commands.append(entry)
    profile = {
        "id": profile_id,
        "title": title,
        "generated_by": "tools/gsfirmware/profile_from_source.py",
        "dispatch": {"kind": "stock_split", "pc": "COMINT", "table": "COMTAB", "tableHigh": "COMTABH",
                     "unknownStub": "COMZ"},
        "commands": commands,
    }
    if symbol_file:
        profile["symbolFile"] = symbol_file
    found = structs(lines)
    if found:
        profile["structs"] = found
    return json.dumps(profile, indent=2, ensure_ascii=False) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--write", action="store_true", help="overwrite the committed profiles")
    parser.add_argument("--source")
    parser.add_argument("--patch", help="a folder of patches writing COMTABH entries (ORG COMTABH+#NN-#20)")
    parser.add_argument("--map")
    parser.add_argument("--id")
    parser.add_argument("--title")
    parser.add_argument("--symbol-file")
    parser.add_argument("--out")
    args = parser.parse_args()
    if args.source:
        text = generate(args.source, args.map, args.id, args.title or args.id, args.symbol_file, args.patch)
        if args.out:
            with open(args.out, "w", encoding="utf-8") as f:
                f.write(text)
        else:
            sys.stdout.write(text)
        return 0
    differ = 0
    for p in COMMITTED:
        text = generate(p["source"], p["map"], p["id"], p["title"], p["symbol_file"], p.get("patch"))
        old = open(p["out"], encoding="utf-8").read() if os.path.exists(p["out"]) else None
        rel = os.path.relpath(p["out"], ROOT)
        if args.write:
            with open(p["out"], "w", encoding="utf-8") as f:
                f.write(text)
            print(f"wrote {rel}")
        elif old != text:
            print(f"{rel}: differs from the sources (run with --write)")
            differ = 1
        else:
            print(f"{rel}: equal")
    return differ


if __name__ == "__main__":
    sys.exit(main())
